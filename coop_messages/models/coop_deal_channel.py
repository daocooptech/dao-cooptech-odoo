# -*- coding: utf-8 -*-
"""Состав чата сделки — её стороны.

До 16 сентября 2026 состав был случайным: демо-загрузчик сажал в каждый
чат «себя», чтобы было что показать, и в 28 чатах из 30 сидели не те
люди. С правилом видимости это означало бы прямое: человек читает чужую
сделку и не видит своей.
"""

from odoo import api, models


class CoopDeal(models.Model):
    _name = 'coop.deal'
    _inherit = ['coop.deal', 'coop.channel.sync']

    def _coop_channel_partners(self):
        """Обе стороны, каждая развёрнута в людей: подписант и ведущий.

        Стороной сделки бывает организация, а у организации нет учётной
        записи — читать чат некому.

        Сначала разворачивали по полномочию «Переписка и заявки», и
        сверка показала, чем это кончается: чат сделки выходил на девять
        человек в среднем и на двадцать в худшем случае, потому что
        переписку в организациях поручают многим. Переговоры по сделке на
        двадцать человек — это уже не переговоры.

        Владелец 16 сентября 2026 сузил: **подписант и ведущий сделку**.
        Подписант — право подписи без доверенности, он в организации один;
        ведущий — полномочие «Сделки». Плюс тот, кто эту сделку завёл: он
        её ведёт по факту, каким бы полномочием ни обладал. Остальных при
        нужде зовут руками — и такой чат платформа уже не трогает.
        """
        self.ensure_one()
        люди = self.env['res.partner']
        for сторона in (self.party_a_id | self.party_b_id):
            if not сторона.is_company:
                люди |= сторона
                continue
            люди |= сторона.coop_power_holders('sign')
            люди |= сторона.coop_power_holders('deal')
        # Заведший сделку — в чате всегда: он с ней и работает. Если он
        # человек со стороны, он уже попал выше; если вёл её от имени
        # организации без полномочий, без этой строки он остался бы вне
        # разговора, который сам и начал.
        if self.author_id and not self.author_id.is_company:
            люди |= self.author_id
        return люди

    # Состояния, в которых сделке ещё есть о чём говорить. Решение
    # владельца 16 сентября 2026: переписку заводим только действующим —
    # завершённой и отменённой она больше не нужна, а заводить её задним
    # числом пяти сотням закрытых сделок значит засыпать список мёртвыми
    # разговорами.
    ЖИВЫЕ_СОСТОЯНИЯ = ('draft', 'agreed', 'active', 'acceptance', 'disputed')

    def _coop_channel_specs(self):
        """Одна переписка на сделку: номер и предмет в названии, стороны
        в подписи — по ней в списке отличают одну поставку от другой, не
        открывая."""
        self.ensure_one()
        if self.state not in self.ЖИВЫЕ_СОСТОЯНИЯ:
            return []
        return [{
            'kind': 'deal',
            'name': self.display_name,
            'subtitle': ' · '.join(filter(None, [
                self.party_a_id.display_name, self.party_b_id.display_name])),
            'partners': self._coop_channel_partners(),
        }]

    @api.model_create_multi
    def create(self, vals_list):
        """Новая сделка получает переписку сразу.

        Не отложенно и не по первой реплике: стороны должны увидеть, где
        договариваться, в тот же момент, когда сделка появилась.
        """
        сделки = super().create(vals_list)
        сделки._coop_ensure_channel()
        сделки._coop_sync_channels()
        return сделки

    def write(self, vals):
        """Сменились стороны — сменился и состав переписки.

        Иначе прежний представитель остаётся читать чужой разговор, а
        новый в него не попадает: то самое, что чинили сведением
        составов 16 сентября 2026.
        """
        res = super().write(vals)
        if {'party_a_id', 'party_b_id', 'author_id'} & set(vals):
            self._coop_sync_channels()
        # Сделка ожила — переписка нужна: из переговоров в исполнение
        # сделка попадает и без нашего участия, загрузкой данных или
        # переносом.
        if 'state' in vals:
            self._coop_ensure_channel()
        return res
