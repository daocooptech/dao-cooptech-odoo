# -*- coding: utf-8 -*-
"""Состав переписки следует за составом записи.

Решение владельца 328 от 16 сентября 2026: платформа сама заводит и сама
же держит состав в четырёх переписках — чат сделки, чат проекта, рабочий
чат организации и чат пайщиков кооператива. Чат сообщества заводит
организатор, но состав там тоже наш: участники сообщества.

Всё остальное — чаты, заведённые людьми руками, — платформа не трогает:
у одной организации их может быть сколько угодно, и состав каждого ведёт
тот, кто его завёл.

Почему состав — записи участников, а не вычисляемое поле: у записи
участника есть своё состояние (граница непрочитанного, отметка
прочтения, закрепление, своё имя чата), и пересчёт вычислением стирал бы
его при каждом изменении членства. Движок к тому же берёт состав отсюда
везде — счётчик непрочитанного, подписка на живую доставку, «печатает…»;
участника, которого нет в этой таблице, он на доставку не подпишет.
"""

from odoo import api, fields, models


class CoopChannelSync(models.AbstractModel):
    """Примесь для моделей, у которых есть своя переписка.

    Модель-источник объявляет два метода: как найти свои каналы и кто в
    них должен состоять. Всё остальное — сверка и запись — здесь, чтобы
    правило было одно на все разделы, а не пять похожих.
    """

    _name = 'coop.channel.sync'
    _description = 'Состав переписки по составу записи'

    def _coop_channels(self):
        """Переписки этой записи, состав которых ведёт платформа.

        Ищутся обратной ссылкой, а не полем на записи: у одной записи
        переписок бывает несколько. Признак `coop_managed` отделяет
        заведённые платформой от заведённых руками — во вторые платформа
        не вмешивается.
        """
        self.ensure_one()
        if not self.id:
            return self.env['discuss.channel']
        return self.env['discuss.channel'].sudo().search([
            ('coop_res_model', '=', self._name),
            ('coop_res_id', '=', self.id),
            ('coop_managed', '=', True),
        ])

    def _coop_channel_partners(self):
        """Кто должен состоять в переписке. Переопределяется.

        Возвращает `res.partner` — людей, а не организации: у организации
        нет учётной записи, и канал с одной организацией в составе не
        читает никто.
        """
        return self.env['res.partner']

    def _coop_sync_channels(self):
        """Привести состав переписок в соответствие с записью.

        Добавляем недостающих, убираем лишних. Убираем так же осознанно,
        как добавляем: человек, вышедший из кооператива, остаётся в чате
        ровно до того, как об этом узнает эта строка.
        """
        for record in self:
            каналы = record._coop_channels()
            if not каналы:
                continue
            должны = record._coop_channel_partners()
            for канал in каналы:
                record._coop_apply_members(канал, должны)
        return True

    @api.model
    def _coop_ensure_group(self, channel, partners):
        """Переписка двоих не вмещает третьего — поднимаем до групповой.

        У движка `chat` — это именно разговор двоих, и на третьего
        участника он отвечает отказом: «designed for just two people».
        Чаты сделок заведены такими, а состав по решению владельца шире:
        подписант и ведущий с каждой стороны.

        Менять вид канала обычной записью движок тоже запрещает
        (`discuss.channel.write`), поэтому вид поднимается запросом к
        базе. Случай разовый: новые переписки платформа заводит сразу
        групповыми, а существующие надо перевести один раз.

        Поднимаем всякий раз, когда состав такой переписки ведёт
        платформа, а не только когда людей больше двух: движок запрещает
        добавлять в переписку двоих **кого бы то ни было**, даже взамен
        выбывшего. Условие в его проверке — «тип chat и участник уже
        есть», а не «участников станет больше двух».

        Обратно не понижаем: переписка, однажды ставшая групповой, при
        уходе участника не должна превращаться в личную — у неё есть
        название и история, которые в личной переписке не показываются.
        """
        if channel.channel_type != 'chat':
            return False
        self.env.cr.execute(
            "UPDATE discuss_channel SET channel_type = 'group' WHERE id = %s",
            (channel.id,))
        channel.invalidate_recordset(['channel_type'])
        return True

    @api.model
    def _coop_apply_members(self, channel, partners):
        """Разница между тем, кто есть, и тем, кто должен быть."""
        self._coop_ensure_group(channel, partners)
        Member = self.env['discuss.channel.member'].sudo()
        есть = channel.sudo().channel_member_ids
        есть_партнёры = есть.mapped('partner_id')
        лишние = есть.filtered(
            lambda m: m.partner_id and m.partner_id not in partners)
        недостающие = partners - есть_партнёры
        if лишние:
            лишние.unlink()
        if недостающие:
            Member.create([{
                'channel_id': channel.id,
                'partner_id': партнёр.id,
            } for партнёр in недостающие])
        return len(недостающие), len(лишние)
