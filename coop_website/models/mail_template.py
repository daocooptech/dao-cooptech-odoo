# -*- coding: utf-8 -*-
from odoo import models


class MailTemplate(models.Model):
    """Письмо о заведённой учётной записи можно не отправлять.

    Штатная регистрация Odoo отправляет письмо сразу, в том же запросе
    (`force_send=True`). Если исходящего почтового сервера на узле нет,
    отправка падает с `UserError`, и человек видит сообщение об ошибке —
    хотя учётная запись уже создана и войти под ней можно. Со стороны
    это выглядит как «регистрация не работает».

    Пока почта не настроена, письмо не отправляется вовсе: решение
    владельца от 15 сентября 2026 — на время испытаний участник заводит
    учётную запись и сразу входит по логину и паролю.

    Сделано признаком в окружении, а не правкой контроллера: он ставится
    только нашим обработчиком регистрации, и на все остальные письма
    платформы это не влияет никак.
    """
    _inherit = 'mail.template'

    def send_mail(self, res_id, **kwargs):
        if self.env.context.get('coop_skip_signup_mail'):
            return False
        return super().send_mail(res_id, **kwargs)
