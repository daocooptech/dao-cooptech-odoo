# -*- coding: utf-8 -*-
"""Способы расчёта: справочник с ценой каждого.

Решение 387 от 22 сентября 2026. Владелец: **«Показывать всё, но с
ценой»** — это отклонение рекомендации бухгалтера, который предлагал
спрятать уступку требования и ЦФА.

Отчего владелец выбрал прозрачность: спрятанный способ не исчезает, он
уходит из платформы наружу, где никто не предупредит о шестидесяти
процентах маржи. Платформа, которая скрывает дорогое вместо того, чтобы
назвать цену, учит не доверять и остальным её подсказкам.

**Четыре состояния.** Владелец 23 сентября 2026 поправил прежние три:

> «это не так, всё это будет и будет в рамках закона, в том числе цфа и
> криптовалюты… крипта тоже не запрещена, запрещена оплата, мы делаем
> функционал биржи»

Поправка по существу, а не по формулировке. Прежняя запись называла
запрещённым **инструмент**, тогда как запрещён **способ его применения**:

* цифровая валюта — ею нельзя расплачиваться за товары и услуги в
  России, но владеть, обменивать и торговать ею не запрещено, и биржа
  — это как раз обмен, а не оплата;
* ЦФА — внутри страны не средство платежа, но по внешнеторговым
  договорам разрешены прямо, и выпуск с обращением идут через оператора
  информационной системы;
* валюта — между двумя резидентами нельзя, между резидентом и
  нерезидентом **можно**, через уполномоченный банк. Без этого не
  бывает ни международной сделки, ни расчёта внутри БРИКС.

Отсюда состояния:

* `promoted` — дёшево и законно, платформа предлагает сама;
* `priced` — законно, но дорого: показываем вместе с ценой;
* `conditional` — законно **при условии**: нужен статус, посредник или
  вид сделки. Условие написано рядом, а не спрятано;
* `planned` — платформа этого ещё не умеет, но будет. Пункт стоит и
  говорит, чего ждать.

Состояния `denied` больше нет. Запрещён не способ, а применение: это
описывается условием, и условие — часть устройства, а не отказ.

Цена в процентах — из разбора бухгалтера от 22 сентября
(`Матчасть/accountant/2026-09-22 — Во что обходится каждый способ расчёта`).
Она сквозная: всё, что уходит в бюджет с обеих сторон вместе.
"""
from odoo import fields, models


class CoopSettlementMethod(models.Model):
    _name = 'coop.settlement.method'
    _description = 'Способ расчёта'
    _order = 'sequence, name'

    name = fields.Char(string='Название', required=True, translate=True)
    code = fields.Char(string='Код', required=True, index=True)
    sequence = fields.Integer(string='Порядок', default=10)
    active = fields.Boolean(default=True)

    status = fields.Selection([
        ('promoted', 'Предлагаем'),
        ('priced', 'Доступно, с ценой'),
        ('conditional', 'При условии'),
        ('planned', 'Готовится'),
    ], string='Как показываем', default='priced', required=True, index=True)

    # Что должно сойтись, чтобы способ заработал. Не «нельзя», а «нужно
    # вот это»: статус оператора, уполномоченный банк, внешнеторговый
    # договор. Разница не в вежливости — из «нельзя» не следует плана, из
    # условия следует.
    condition = fields.Text(
        string='Что нужно, чтобы работало',
        help='Условие законности и техническая готовность. Пишется так, '
             'чтобы из него было видно, что делать дальше.')
    legal_basis = fields.Char(
        string='Правовое основание',
        help='Норма, по которой способ работает или ограничен.')
    cross_border = fields.Boolean(
        string='Годится для международных',
        help='Работает ли способ между резидентом и нерезидентом.')

    cost_hint = fields.Char(
        string='Во что обходится',
        help='Сквозная цена: всё, что уходит в бюджет с обеих сторон '
             'вместе. Из разбора бухгалтера.')
    cost_note = fields.Text(
        string='Отчего столько',
        help='Одной фразой — почему цена такая. Без этого число выглядит '
             'придиркой платформы, а не законом.')


    _code_unique = models.Constraint(
        'unique(code)',
        'Код способа расчёта занят.',
    )
