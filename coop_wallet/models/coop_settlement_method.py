# -*- coding: utf-8 -*-
"""Способы расчёта: справочник с ценой каждого.

Решение 387 от 22 сентября 2026. Владелец: **«Показывать всё, но с
ценой»** — это отклонение рекомендации бухгалтера, который предлагал
спрятать уступку требования и ЦФА.

Отчего владелец выбрал прозрачность: спрятанный способ не исчезает, он
уходит из платформы наружу, где никто не предупредит о шестидесяти
процентах маржи. Платформа, которая скрывает дорогое вместо того, чтобы
назвать цену, учит не доверять и остальным её подсказкам.

**Три состояния, а не два.** Решение «показывать всё» относится к
дорогому, а не к запрещённому — это разные вещи, и смешивать их нельзя:

* `promoted` — дёшево и законно, платформа предлагает сама;
* `priced` — законно, но дорого: показываем вместе с ценой;
* `denied` — нельзя. В списке выбора такого нет ни с какой ценой.

Цена в процентах — из разбора бухгалтера от 22 сентября
(`Матчасть/accountant/2026-09-22 — Во что обходится каждый способ расчёта`).
Она сквозная: всё, что уходит в бюджет с обеих сторон вместе.
"""
from odoo import fields, models


class CoopSettlementMethod(models.Model):
    _name = 'coop.settlement.method'
    _description = 'Способ расчёта'
    _order = 'sequence, name'

    name = fields.Char(string='Название', required=True, translate=True)
    code = fields.Char(string='Код', required=True, index=True)
    sequence = fields.Integer(string='Порядок', default=10)
    active = fields.Boolean(default=True)

    status = fields.Selection([
        ('promoted', 'Предлагаем'),
        ('priced', 'Показываем с ценой'),
        ('denied', 'Нельзя'),
    ], string='Как показываем', default='priced', required=True, index=True)

    cost_hint = fields.Char(
        string='Во что обходится',
        help='Сквозная цена: всё, что уходит в бюджет с обеих сторон '
             'вместе. Из разбора бухгалтера.')
    cost_note = fields.Text(
        string='Отчего столько',
        help='Одной фразой — почему цена такая. Без этого число выглядит '
             'придиркой платформы, а не законом.')
    deny_reason = fields.Char(
        string='Отчего нельзя',
        help='Норма, по которой способ запрещён. Нужна не для человека, '
             'а для того, кто через год спросит, почему его нет.')

    _code_unique = models.Constraint(
        'unique(code)',
        'Код способа расчёта занят.',
    )
