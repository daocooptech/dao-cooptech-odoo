# -*- coding: utf-8 -*-
"""Справочник форм собственности и налоговых режимов.

Участник, затевающий проект, выбирает не «экономическую модель вообще»,
а вполне конкретную связку: ООО на упрощёнке, ИП на патенте,
производственный кооператив на общей системе. Связка определяет, кто
принимает решения, сколько уходит в бюджет, что сдавать и чем отвечать.

Отсюда устройство справочника: **строка — это форма плюс режим**, а не
форма отдельно и режим отдельно. Сочетания не свободны — патент бывает
только у предпринимателя, самозанятость несовместима с наймом, у
автоматизированной упрощёнки свой список регионов, — и таблица
допустимых сочетаний и есть то, ради чего справочник заводится. Держать
два независимых поля значило бы позволить выбрать невозможное.

Кооперативы отличаются от прочих форм тем, что внутри одной и той же
правовой оболочки работают разные уклады: распределение по Чартаеву,
периодическая сверка по Водянову («Компас»), простое распределение по
уставу. Это **не налоговый режим и не форма**, поэтому уклад вынесен во
второе поле и предлагается только там, где имеет смысл.

Числа здесь — со сроком годности. Лимиты и пороги меняются ежегодно и
частью уже расписаны вперёд, поэтому у каждой строки есть дата сверки и
границы действия: справочник, молча соврав участнику про лимит, стоит
дороже, чем его отсутствие.
"""
from odoo import _, api, fields, models
from odoo.exceptions import ValidationError

# Группы нужны, чтобы выпадающий список не превратился в простыню из
# шестидесяти строк: участник сначала понимает, про что вообще речь.
FORM_GROUPS = [
    ('none', 'Без регистрации'),
    ('ip', 'Индивидуальный предприниматель'),
    ('kfh', 'Крестьянское фермерское хозяйство'),
    ('company', 'Хозяйственные общества'),
    ('prodcoop', 'Производственные кооперативы'),
    ('consumercoop', 'Потребительские кооперативы'),
    ('nko', 'Некоммерческие организации'),
    ('partnership', 'Объединения без юридического лица'),
]

TAX_REGIMES = [
    ('none', 'Без налогового режима'),
    ('npd', 'НПД — налог на профессиональный доход'),
    ('psn', 'ПСН — патент'),
    ('usn_income', 'УСН «доходы»'),
    ('usn_income_expense', 'УСН «доходы минус расходы»'),
    ('ausn_income', 'АУСН «доходы»'),
    ('ausn_income_expense', 'АУСН «доходы минус расходы»'),
    ('eskhn', 'ЕСХН — единый сельскохозяйственный налог'),
    ('osno', 'ОСНО — общая система'),
]


class CoopEconomicModel(models.Model):
    _name = 'coop.economic.model'
    _description = 'Форма собственности и налоговый режим'
    _order = 'sequence, name'

    key = fields.Char(
        string='Ключ', required=True, index=True,
        help='Технический ключ строки: по нему на неё ссылаются код и '
             'перенос данных. Латиницей, не меняется после публикации.')
    name = fields.Char(string='Название', required=True, translate=True)
    sequence = fields.Integer(default=100)
    active = fields.Boolean(default=True)

    form_group = fields.Selection(
        FORM_GROUPS, string='Группа', required=True, index=True)
    form_name = fields.Char(
        string='Правовая форма', required=True,
        help='Полное название формы: «Общество с ограниченной '
             'ответственностью», «Производственный кооператив».')
    # Справочник правовых форм на платформе уже есть — двадцать девять
    # форм в coop_base, на них ссылаются организации участников. Своя
    # копия развела бы два списка, которые разойдутся при первой правке,
    # поэтому здесь ссылка, а не дубль. Пусто там, где формы нет вовсе:
    # у самозанятого и у товарищества юридического лица не возникает.
    legal_form_id = fields.Many2one(
        'coop.legal.form', string='Форма в справочнике платформы',
        ondelete='set null', index=True,
        help='Та же форма, что стоит у организаций участников. Пусто у '
             'конструкций без юридического лица.')
    regime = fields.Selection(
        TAX_REGIMES, string='Налоговый режим', required=True, index=True)

    summary = fields.Char(
        string='Одной строкой', required=True,
        help='То, что видно в списке рядом с названием. Не пересказ '
             'названия, а причина выбрать именно это.')

    # ── Пояснения под выбранной строкой ──────────────────────────────────
    #
    # Решение владельца от 2026-09-14: под выбранной формой разворачивается
    # разбор — управление, налоги, отчётность, ответственность,
    # ограничения — и отдельно то, что важно знать вкладывающемуся.
    # Последнее нужно не основателю, а инвестору, читающему карточку
    # чужого проекта, и пишется другими словами.
    management = fields.Html(
        string='Управление', sanitize=False,
        help='Кто принимает решения, как считаются голоса, кто отвечает '
             'за текущую работу.')
    taxes = fields.Html(
        string='Налоги и взносы', sanitize=False,
        help='Ставка, база, страховые взносы, что с выплатами участникам.')
    reporting = fields.Html(
        string='Отчётность', sanitize=False,
        help='Что и когда сдавать, нужен ли бухгалтер, нужна ли касса.')
    liability = fields.Html(
        string='Ответственность', sanitize=False,
        help='Чем отвечают по долгам — имуществом организации, личным '
             'имуществом, субсидиарно.')
    limits = fields.Html(
        string='Ограничения', sanitize=False,
        help='Пределы дохода и численности, запрещённые виды '
             'деятельности, требования к составу участников.')
    for_investor = fields.Html(
        string='Что важно вкладывающемуся', sanitize=False,
        help='На что смотрит тот, кто собирается вложиться в проект с '
             'такой формой: чем закрепляется его доля, как выйти, на что '
             'он может влиять, чем рискует.')
    warning = fields.Html(
        string='Предупреждение', sanitize=False,
        help='Показывается отдельно и заметно. Заполняется только там, '
             'где выбор чаще всего оказывается ошибкой.')

    # ── Проверяемые признаки ─────────────────────────────────────────────
    #
    # Всё, что можно проверить машиной, лежит полями, а не текстом:
    # текстом это ровно та подсказка, которую участник не прочитает.
    requires_registration = fields.Boolean(
        string='Нужна регистрация', default=True,
        help='Нужен ОГРН или ОГРНИП. Снято у самозанятого без статуса '
             'предпринимателя и у объединений без юрлица.')
    can_hire = fields.Boolean(
        string='Можно нанимать', default=True,
        help='У самозанятого наёмных работников не бывает вовсе — это '
             'не ограничение по числу, а запрет.')
    region_dependent = fields.Boolean(
        string='Зависит от региона',
        help='Патент и автоматизированная упрощёнка действуют не везде и '
             'не для всех видов деятельности.')
    min_members = fields.Integer(
        string='Минимум участников',
        help='У производственного кооператива их пять. Ноль — требования нет.')
    # Состав членов — не признак кооператива вообще, а свойство
    # конкретного вида. Кооперативы бывают из одних граждан, из одних
    # организаций и смешанные; попытка считать, что члены всегда
    # граждане, запретила бы участнику то, что закон разрешает.
    #
    # Значений пять, а не три. Ассоциированное членство — отдельный
    # случай: в сельхозпроизводственном кооперативе организация членом
    # быть не может вовсе, но может войти ассоциированным членом с
    # правом на доход и без права голоса. Свести это к «только граждане»
    # значит соврать, к «граждане и организации» — соврать иначе.
    member_composition = fields.Selection([
        ('citizens_only', 'Только граждане'),
        ('citizens_and_orgs', 'Граждане и организации'),
        ('orgs_only_allowed',
         'Граждане и организации, допустим состав только из организаций'),
        ('citizens_orgs_as_associate',
         'Только граждане; организации — ассоциированными членами'),
        ('n/a', 'Не применимо'),
    ], string='Состав членов', default='n/a', required=True,
        help='У форм без членства стоит «не применимо»: у общества '
             'участники, а не члены, и правила там другие.')
    members_note = fields.Char(
        string='Оговорка о составе',
        help='Что показать участнику при выборе: через кого действует '
             'организация-член, какие пределы, что закрепить уставом.')

    # Потолок участия организаций. У производственного кооператива он
    # нужен сразу в двух измерениях — по паевому фонду и по числу
    # членов, — потому что неизвестно, каким из двух способов инспектор
    # посчитает «долю участия других организаций» для упрощёнки. Устав,
    # удерживающий оба ниже порога, снимает спор до того, как он возник.
    #
    # У потребительских кооперативов ограничения нет вовсе: они
    # некоммерческие, и норма про двадцать пять процентов на них не
    # распространяется. Показывать им это предупреждение нельзя —
    # ложная тревога обесценивает справочник целиком.
    org_share_cap = fields.Integer(
        string='Предел участия организаций, %',
        help='Ноль — предела нет. У производственного кооператива '
             'двадцать пять, и считать надо и по паям, и по числу '
             'членов одновременно.')
    requires_charter_clause = fields.Boolean(
        string='Нужна оговорка в уставе',
        help='Организация становится членом только там, где устав это '
             'прямо разрешает. Промолчавший устав — запрет.')
    org_acts_via_representative = fields.Boolean(
        string='Организация действует через представителя',
        help='Юридическое лицо не может участвовать лично: права члена '
             'осуществляет представитель по доверенности.')
    income_limit = fields.Float(
        string='Предел дохода, ₽', digits=(16, 0),
        help='Ноль — предела нет.')
    employee_limit = fields.Integer(
        string='Предел работников', help='Ноль — предела нет.')
    vat_exempt_limit = fields.Float(
        string='Порог освобождения от НДС, ₽', digits=(16, 0))

    legal_basis = fields.Char(
        string='Основание',
        help='Статьи и законы, на которых держится строка. По ним потом '
             'проверяют, не устарела ли она.')

    # ── Срок годности ────────────────────────────────────────────────────
    checked_on = fields.Date(
        string='Числа сверены', required=True,
        help='Когда строку последний раз сверяли с НК и законами. '
             'Справочник, соврав про лимит, дороже отсутствующего.')
    valid_from = fields.Date(string='Действует с')
    valid_to = fields.Date(
        string='Действует по',
        help='Заполнено у режимов с заранее назначенным концом: '
             'автоматизированная упрощёнка и самозанятость — эксперименты '
             'с датой окончания.')
    is_expiring = fields.Boolean(
        string='Заканчивается', compute='_compute_is_expiring', store=True)

    scheme_ids = fields.Many2many(
        'coop.economic.scheme', string='Возможные уклады',
        help='Заполняется у кооперативов: внутри одной формы работают '
             'разные способы распределения.')

    project_count = fields.Integer(
        string='Проектов', compute='_compute_project_count')

    _key_uniq = models.Constraint('unique(key)',
                                  'Ключ строки справочника должен быть уникальным.')

    @api.depends('valid_to')
    def _compute_is_expiring(self):
        for record in self:
            record.is_expiring = bool(record.valid_to)

    def _compute_project_count(self):
        counts = {}
        if 'coop.project' in self.env:
            grouped = self.env['coop.project'].sudo()._read_group(
                [('economic_model_id', 'in', self.ids)],
                ['economic_model_id'], ['__count'])
            # В Odoo 19 `_read_group` возвращает кортежи записей, а не
            # словари: первым элементом идёт сама запись связи.
            counts = {form.id: count for form, count in grouped}
        for record in self:
            record.project_count = counts.get(record.id, 0)

    @api.constrains('can_hire', 'employee_limit')
    def _check_hiring(self):
        for record in self:
            if not record.can_hire and record.employee_limit:
                raise ValidationError(_(
                    'У формы «%(name)s» нанимать нельзя вовсе, поэтому '
                    'предел работников заполнять бессмысленно.',
                    name=record.name))

    @api.depends('name', 'summary')
    def _compute_display_name(self):
        for record in self:
            record.display_name = record.name


class CoopEconomicScheme(models.Model):
    """Уклад кооператива: как внутри формы устроено распределение.

    Отдельной моделью, а не значением у формы: укладов немного, они
    описываются так же подробно, как формы, и один и тот же уклад
    подходит нескольким кооперативным формам сразу.

    Юридически это всё та же форма — производственный кооператив по
    41-ФЗ. Разница живёт в уставе: трудовые отношения членов кооператива
    Трудовой кодекс не регулирует, а порядок распределения прибыли закон
    отдаёт уставу целиком. Отсюда и возможность разных укладов, и
    требование к платформе — проверять то, что уставом обойти нельзя.
    """
    _name = 'coop.economic.scheme'
    _description = 'Уклад кооператива'
    _order = 'sequence, name'

    key = fields.Char(string='Ключ', required=True, index=True)
    name = fields.Char(string='Название', required=True, translate=True)
    sequence = fields.Integer(default=100)
    active = fields.Boolean(default=True)

    summary = fields.Char(string='Одной строкой', required=True)
    description = fields.Html(string='Как устроено', sanitize=False)
    distribution = fields.Html(
        string='Как делится результат', sanitize=False,
        help='Главное отличие укладов друг от друга.')
    for_investor = fields.Html(
        string='Что важно вкладывающемуся', sanitize=False)
    charter_notes = fields.Html(
        string='Что закрепить уставом', sanitize=False,
        help='Уклад работает только через устав. Здесь то, без чего он '
             'останется картинкой на экране.')
    warning = fields.Html(string='Предупреждение', sanitize=False)
    legal_basis = fields.Char(string='Основание')
    checked_on = fields.Date(string='Сверено', required=True)

    form_ids = fields.Many2many('coop.economic.model', string='Где применим')

    _key_uniq = models.Constraint('unique(key)',
                                  'Ключ уклада должен быть уникальным.')
