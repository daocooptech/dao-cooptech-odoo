DASH = ' — '


def _text(name):
    """Описание рабочего проекта по названию «Тема, этап» или «Тема — Город»."""
    base, city, stage = name, '', ''
    if DASH in base:
        base, city = base.split(DASH, 1)
    if ', ' in base:
        base, stage = base.split(', ', 1)
    parts = [THEMES.get(base.strip()) or (
        '%s: рабочий проект без сбора вкладов. Задачи, вехи и сроки ведём '
        'здесь, ход работ — в ленте проекта.' % name)]
    if stage.strip() in STAGES:
        parts.append(STAGES[stage.strip()])
    if city.strip():
        parts.append('Место работ — %s; исполнителей и поставщиков ищем '
                     'сначала там же.' % city.strip())
    return ''.join('<p>%s</p>' % escape(p) for p in parts)


def migrate(cr, version):
    empty = "(p.description IS NULL OR p.description IN ('', '<p><br></p>'))"
    # Выросшие из сбора — описание карточки сбора.
    cr.execute("""
        UPDATE project_project p
           SET description = c.description
          FROM (SELECT DISTINCT ON (project_id) project_id, description
                  FROM coop_project
                 WHERE project_id IS NOT NULL
                   AND COALESCE(description, '') NOT IN ('', '<p><br></p>')
                 ORDER BY project_id, id) c
         WHERE c.project_id = p.id AND p.active AND %s
    """ % empty)
    # Рабочие — по названию.
    cr.execute("""
        SELECT p.id, COALESCE(NULLIF(p.name->>'ru_RU', ''), p.name->>'en_US')
          FROM project_project p
         WHERE p.active AND %s
           AND NOT EXISTS (SELECT 1 FROM coop_project c WHERE c.project_id = p.id)
    """ % empty)
    for pid, name in cr.fetchall():
        if name:
            cr.execute('UPDATE project_project SET description = %s WHERE id = %s',
                       (_text(name), pid))
