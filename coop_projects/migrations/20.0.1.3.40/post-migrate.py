def migrate(cr, version):
    # Сопоставление — в Python: в базе с локалью C `lower()` и `~*`
    # русские буквы не понижают.
    cr.execute('SELECT name, id FROM coop_specialization')
    specs = dict(cr.fetchall())
    cr.execute("""
        SELECT id, name FROM coop_resource
         WHERE project_id IS NOT NULL AND resource_type = 'labour'
           AND need_specialization_id IS NULL""")
    for need_id, name in cr.fetchall():
        for pattern, spec in RULES:
            if spec in specs and re.match(pattern, (name or '').strip().lower()):
                cr.execute('UPDATE coop_resource SET need_specialization_id = %s'
                           ' WHERE id = %s', (specs[spec], need_id))
                break
