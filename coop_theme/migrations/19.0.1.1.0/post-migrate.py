# -*- coding: utf-8 -*-
"""Переименовать разделы в уже собранных панелях.

Панель платформы хранится **у каждого участника своя** (193 набора на
23 сентября 2026). Правка списка разделов в коде меняет только то, что
получат новые: у заведённых панель уже есть, и раздел остаётся в ней под
прежним именем.

Владелец 23 сентября: штатный складской модуль зовётся «Управление
складом», наш раздел — «Склады». Без этого прохода 193 участника
продолжали бы видеть «Склад» и не понимать, про какой из двух речь.

**Дубль обязателен к разбору.** Сверка разделов считает «Склады» новым
расширением и дописывает его всем, у кого его нет, — а «Склад» при этом
остаётся. Если обновление темы прошло раньше, чем появился этот перенос
(ровно так и вышло 23 сентября), у участника оказываются оба. Тогда
оставляем **старый**, переименовав его: в нём сохранены место в списке и
то, что участник с ним делал.
"""
import logging

_logger = logging.getLogger(__name__)

RENAMES = [
    ('Склад', 'Склады'),
]


def migrate(cr, version):
    if not version:
        return
    for old, new in RENAMES:
        # Сначала убираем дубли: у кого есть и старый, и новый, — новый
        # лишний. Старый несёт место в списке и решение участника.
        cr.execute("""
            DELETE FROM coop_sidebar_item AS fresh
             USING coop_sidebar_item AS kept
             WHERE fresh.name = %s
               AND kept.name = %s
               AND kept.user_id = fresh.user_id
        """, (new, old))
        dropped = cr.rowcount

        cr.execute("""
            UPDATE coop_sidebar_item SET name = %s WHERE name = %s
        """, (new, old))
        renamed = cr.rowcount

        # Список уже предложенных расширений знает раздел по имени. Не
        # переименовав его, мы предложили бы «Склады» заново тем, кто
        # «Склад» себе убрал.
        cr.execute("""
            UPDATE res_users
               SET coop_sidebar_defaults =
                   replace(coop_sidebar_defaults, %s, %s)
             WHERE coop_sidebar_defaults LIKE %s
        """, ('"%s"' % old, '"%s"' % new, '%"' + old + '"%'))

        _logger.info('Панель: «%s» → «%s»: переименовано %s, убрано '
                     'дублей %s', old, new, renamed, dropped)
