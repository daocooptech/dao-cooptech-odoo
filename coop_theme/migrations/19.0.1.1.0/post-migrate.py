# -*- coding: utf-8 -*-
"""Переименовать разделы в уже собранных панелях.

Панель платформы хранится **у каждого участника своя** (193 набора на
23 сентября 2026). Правка списка разделов в коде меняет только то, что
получат новые: у заведённых панель уже есть, и раздел в ней остаётся под
прежним именем.

Владелец 23 сентября: штатный складской модуль зовётся «Управление
складом», наш раздел — «Склады». Без этого прохода 193 участника
продолжали бы видеть «Склад» и не понимать, про какой из двух речь.

Переименование, а не пересоздание: пункт участник мог переставить или
убрать, и заводить его заново значило бы вернуть убранное.
"""
import logging

_logger = logging.getLogger(__name__)

RENAMES = [
    ('Склад', 'Склады'),
]


def migrate(cr, version):
    if not version:
        return
    for old, new in RENAMES:
        cr.execute("""
            UPDATE coop_sidebar_item SET name = %s WHERE name = %s
        """, (new, old))
        if cr.rowcount:
            _logger.info('Панель: «%s» → «%s» у %s участников',
                         old, new, cr.rowcount)

        # Список уже предложенных расширений хранится отдельно и тоже
        # знает раздел по имени. Не переименовав его, мы предложили бы
        # «Склады» заново тем, кто «Склад» себе убрал.
        cr.execute("""
            UPDATE res_users
               SET coop_sidebar_defaults = replace(coop_sidebar_defaults, %s, %s)
             WHERE coop_sidebar_defaults LIKE %s
        """, (old, new, '%' + old + '%'))
