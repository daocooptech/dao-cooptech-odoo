/** Имя значка Tabler по имени из пункта меню — Material или уже Tabler. */
export function tablerName(name, fallback = "layout-grid") {
    if (name && TABLER[name]) {
        return name;
    }
    return MATERIAL_TO_TABLER[name] || fallback;
}

/**
 * `<CoopIcon name="wallet" size="18"/>` — контур без собственного цвета.
 * Без `title` значок прячется от чтения с экрана: подпись стоит рядом.
 */
export class CoopIcon extends Component {
    static template = "coop_theme.Icon";
    props = useProps();

    get paths() {
        return TABLER[tablerName(this.props.name)] || [];
    }

    get size() {
        return this.props.size || 16;
    }
}
