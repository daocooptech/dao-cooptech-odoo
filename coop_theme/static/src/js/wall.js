/** @odoo-module **/

import { patch } from "@web/core/utils/patch";
import { FormRenderer } from "@web/views/form/form_renderer";
import { Chatter } from "@mail/chatter/web_portal/chatter";
import { Composer } from "@mail/core/common/composer";
import { Thread } from "@mail/core/common/thread";
import { coopIsPlatformModel } from "@coop_theme/js/platform_page";

// Записи, у которых лента — публичная стена, а не служебная переписка.
//
// Список отвечает только за ВИД ленты: открытое поле публикации,
// «Опубликовать», «Что у вас нового?». Раскладка (лента под карточкой,
// а не сбоку) по нему больше не решается — она общая для всех страниц
// платформы, см. `mailLayout` ниже. Разводить их пришлось потому, что
// теснота карточки не зависит от того, стена перед нами или журнал, а
// приглашение публиковать — очень даже.
export const WALL_MODELS = ["res.partner", "coop.project", "coop.community"];

/**
 * Лента — под карточкой, а не сбоку. На всех страницах платформы.
 *
 * У движка лента (переписка записи) на широком экране уезжает в правую
 * колонку и забирает половину ширины. Для служебной карточки Odoo это
 * верно: там переписка — сопровождение работы с записью, и карточка
 * узкая. У нас карточка широкая: две колонки полей, встроенные списки,
 * полки. В оставшейся половине она не помещается — значения режутся до
 * двух знаков, колонки налезают друг на друга, под списком появляется
 * горизонтальная прокрутка.
 *
 * Сначала правило было узким: только человек, организация, проект и
 * сообщество — там, где лента не переписка, а стена. Владелец
 * 21 сентября 2026, увидев ленту сбоку на карточке склада: «почему
 * опять лента справа? мы этот момент уже прошли». Причина у тесноты одна
 * и та же на всех страницах записей, значит и правило должно быть одно.
 *
 * Теперь по общему признаку платформенной страницы (`coop.*` и
 * `res.partner`). Чужие экраны движка — настройки, пользователи, модули
 * — по-прежнему ведут себя как обычно: переставлять чужой интерфейс
 * целиком значит брать на себя починку после каждого обновления.
 *
 * Раскладка и поведение стены — разные вещи, и списки у них разные.
 * Вниз лента уезжает везде; «Опубликовать» и «Что у вас нового?»
 * остаются только на стенах: в ленте склада лежит служебная запись
 * «Склад создан», и звать там что-то публиковать — неправда.
 */
patch(FormRenderer.prototype, {
    mailLayout(hasAttachmentContainer) {
        const layout = super.mailLayout(hasAttachmentContainer);
        if (!coopIsPlatformModel(this.props.record?.resModel)) {
            return layout;
        }
        // «Ничего» и «вложения сбоку» не трогаем: в первом случае ленты
        // нет вовсе, во втором её и так рисуют снизу.
        if (layout === "SIDE_CHATTER" || layout === "EXTERNAL_COMBO_XXL") {
            return "BOTTOM_CHATTER";
        }
        return layout;
    },
});

// Подпись кнопки публикации — из макета. Через перевод, а не правкой
// разметки движка: кнопка одна на весь Odoo, и подменять её шаблон
// значило бы менять надпись и там, где это действительно переписка.

/**
 * Поле публикации на стене открыто сразу.
 *
 * У переписки записи оно спрятано за кнопкой: там пишут изредка и по
 * поводу. Стена — обратный случай: человек заходит на свою страницу,
 * чтобы что-то рассказать, и лишний щелчок перед пустым полем ничего не
 * экономит. В макете поле стоит открытым, с подсказкой и кнопкой.
 */
patch(Chatter.prototype, {
    setup() {
        super.setup();
        if (WALL_MODELS.includes(this.props.threadModel)) {
            // Не через `toggleComposer`: тот на неспасённой записи ждёт
            // сохранения и открывает поле уже после него. Здесь запись
            // всегда сохранена — это чужая или своя страница, а не форма
            // создания.
            this.state.composerType = "message";
        }
    },

    /**
     * После публикации поле не сворачивается.
     *
     * Движок после отправки зовёт `toggleComposer()` без режима — это
     * расчёт на переписку, где поле по умолчанию спрятано и открывается
     * по кнопке, а «переключить» без аргументов её закрывает обратно.
     * На стене поле открыто всегда типом `message`, и то же
     * переключение читается как «закрой уже открытое» — после первой же
     * публикации шапка с полем ввода пропадала. Возвращаем тип сразу
     * после стандартной обработки (перезагрузки ленты и прочего).
     */
    onPostCallback() {
        super.onPostCallback();
        if (WALL_MODELS.includes(this.props.threadModel)) {
            this.state.composerType = "message";
        }
    },
});

/**
 * Подсказка и подпись кнопки на стене — из макета.
 *
 * «Отправить сообщение подписчикам…» и «Отправить» — слова переписки: там
 * пишут кому-то. Стена устроена иначе, там рассказывают всем сразу, и
 * подпись «Опубликовать» отвечает на другой вопрос — что случится с
 * написанным.
 *
 * Правится через компонент, а не переводом: тот же компонент обслуживает
 * настоящую переписку, где прежние слова верны.
 */
patch(Composer.prototype, {
    get placeholder() {
        if (WALL_MODELS.includes(this.thread?.model)) {
            return "Что у вас нового?";
        }
        return super.placeholder;
    },

    get SEND_TEXT() {
        if (!this.props.composer.message && this.props.type !== "note"
                && WALL_MODELS.includes(this.thread?.model)) {
            return "Опубликовать";
        }
        return super.SEND_TEXT;
    },
});

/**
 * На стене — только то, что написали люди.
 *
 * Лента записи — это и стена, и служебный журнал: туда же движок пишет
 * «Контакт создан», смену состояния («Сбор → Запущен»), приглашения. В
 * переписке по сделке или складу журнал к месту, а на стене человека,
 * организации, проекта, сообщества он читается как чужая запись среди
 * своих. Владелец 24 сентября 2026: «на моей странице внизу лента и там
 * только моя запись 123 и сообщение от бота о создании контакта».
 *
 * Прячется только на стенах (`WALL_MODELS`) и только из показа: журнал
 * остаётся в базе, и в обсуждении прочих записей он виден как прежде.
 * Внутренние заметки (`isNote`) на стене тоже не показываются — они не
 * для всех, а стена для всех.
 */
patch(Thread.prototype, {
    get orderedMessages() {
        const messages = super.orderedMessages;
        if (!WALL_MODELS.includes(this.props.thread?.model)) {
            return messages;
        }
        // По дате, а не по номеру: номер записи — порядок заведения, а
        // не времени. Записи, заведённые задним числом, шли на стене
        // вразнобой — «29 мая, 6 сентября, 12 июля».
        const asc = this.props.order === "asc";
        return messages
            .filter((m) => m.message_type === "comment" && !m.isNote)
            .sort((a, b) => (asc ? 1 : -1) * ((a.datetime - b.datetime) || (a.id - b.id)));
    },
});
