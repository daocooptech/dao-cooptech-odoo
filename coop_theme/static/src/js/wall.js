import { patch } from "@web/core/utils/patch";
import { FormRenderer } from "@web/views/form/form_renderer";

/**
 * Лента участника и организации — под карточкой, а не сбоку.
 *
 * У движка лента (переписка записи) на широком экране уезжает в правую
 * колонку и забирает половину ширины. Для служебной карточки это верно:
 * там переписка — сопровождение работы с записью. У нас же это стена
 * участника из макета: записи человека, которые читают так же, как всё
 * остальное на странице, сверху вниз. Сбоку от неё остаётся полоса в
 * двести пикселей, где плитки идут столбиком.
 *
 * Правило узкое — только карточки людей и организаций. Остальные экраны
 * движка ведут себя как обычно: переставлять чужой интерфейс целиком
 * значит брать на себя починку после каждого обновления.
 */
patch(FormRenderer.prototype, {
    mailLayout(hasAttachmentContainer) {
        const layout = super.mailLayout(hasAttachmentContainer);
        // Стена есть у человека, организации, проекта и сообщества —
        // у каждой записи своя. Служебные экраны движка не трогаем:
        // переставлять чужой интерфейс целиком значит брать на себя
        // починку после каждого обновления.
        const withWall = ["res.partner", "coop.project", "coop.community"];
        if (!withWall.includes(this.props.record?.resModel)) {
            return layout;
        }
        // «Ничего» и «вложения сбоку» не трогаем: в первом случае ленты
        // нет вовсе, во втором её и так рисуют снизу.
        if (layout === "SIDE_CHATTER" || layout === "EXTERNAL_COMBO_XXL") {
            return "BOTTOM_CHATTER";
        }
        return layout;
    },
});

