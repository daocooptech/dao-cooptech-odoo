/** @odoo-module **/

import { patch } from "@web/core/utils/patch";
import { FormController } from "@web/views/form/form_controller";
import { coopIsPlatformModel } from "@coop_theme/js/platform_page";

/**
 * Чужая запись — только чтение, у всех сущностей платформы.
 *
 * Владелец 28.10.2026: «я зашел в чужой проект и давай че то добавлять и
 * править, так быть не должно, надо убрать редактирование и оставить
 * только те пункты которые заполнены и с правами только для чтения, где
 * есть чекбоксы выбора тоже убрать, оставить только сделаный выбор»
 * (задача 391).
 *
 * Почему одним местом, а не разметкой каждой формы. Право правки уже
 * посчитано на записи — `coop_can_edit` в `coop.page.mixin`, — и
 * разложено по полям видами: `readonly="not coop_can_edit"` стоит в
 * шестистах полях. Но разложено руками, и замер 31.10 находит сто
 * шестнадцать полей, до которых правка по месту ещё не дошла, двенадцать
 * встроенных списков, разрешающих добавить строку, и переключатели
 * состояния в шапке. Каждая новая форма и каждое новое поле начинали бы
 * с той же дыры.
 *
 * Где закрыто — на уровне записи, а не поля. Режим модели `readonly`
 * движок понимает везде сразу: поле, встроенный список, изображение,
 * полоса сохранения, автосохранение. Это то же состояние, в котором
 * форма бывает у смотрящего без прав, — не новое поведение, а штатное.
 *
 * Что остаётся работать: кнопки-действия (вклад, отклик, заявка) и
 * вкладки. Они не правят запись, а заводят другую, и для чужой записи
 * это ровно то, ради чего страница открыта.
 */
patch(FormController.prototype, {
    setup() {
        super.setup(...arguments);
        // Метка на странице: по ней стили прячут пустые пункты (см.
        // `foreign.scss`). Классы корня формы движок собирает заново на
        // каждой отрисовке (`className`), поэтому метку ставим там же, а
        // не `classList` на элементе: прибавленный руками класс стёрся бы
        // на первом же обновлении (замер 31.10 — так и вышло).
    },

    get className() {
        const result = super.className;
        if (this.coopForeignClosedFor) {
            result.o_coop_foreign = true;
        }
        return result;
    },

    async onRootLoaded() {
        await super.onRootLoaded(...arguments);
        await this.coopReadonlyForeignPage();
    },

    /**
     * Закрыть правку, если страница платформы открыта на чужую запись.
     *
     * Ошибки глушим: непрочитанное право правки — не повод уронить
     * отрисовку страницы. Не прочиталось — остаётся прежнее поведение,
     * и его видно на следующем замере.
     */
    async coopReadonlyForeignPage() {
        try {
            const root = this.model && this.model.root;
            if (!root || root.isNew || !coopIsPlatformModel(root.resModel)) {
                return;
            }
            if (!root.data || root.data.coop_can_edit !== false) {
                return;
            }
            // Запись уже закрыта — второй заход по кругу: переключение
            // режима само вызывает обновление модели.
            if (this.coopForeignClosedFor === root.resId) {
                return;
            }
            this.coopForeignClosedFor = root.resId;
            await root.switchMode("readonly");
        } catch (error) {
            console.warn("[страница] чужую запись не удалось открыть только для чтения:", error);
        }
    },
});
