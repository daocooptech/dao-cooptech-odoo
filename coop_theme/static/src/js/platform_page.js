/**
 * Страница записи платформы, а не чужого справочника движка.
 *
 * Одно правило на всех, кто его спрашивает: полоса над карточкой (прячет
 * штатное «Меню действий») и полоса сохранения внизу формы (прячет пару
 * «сохранить/отменить» в шапке). Два списка правды разошлись бы при
 * первой же правке, и разошлись бы молча: каждый из них по отдельности
 * выглядел бы работающим.
 *
 * Правило по имени модели, а не по списку разделов бокового меню: список
 * у каждого участника свой, расширения он убирает совсем, и правило,
 * опознанное по нему, вело бы себя по-разному у двух человек на одной и
 * той же странице. Всё, что платформа завела сама, называется `coop.*`;
 * люди и организации стоят на `res.partner`.
 *
 * Чужие экраны движка — настройки, пользователи, модули — правилом не
 * задеты: там и меню записи, и страничное сохранение на месте, и
 * администратору они нужны.
 */
export function coopIsPlatformModel(model) {
    return (
        typeof model === "string" &&
        (model.startsWith("coop.") || model === "res.partner")
    );
}

/**
 * Модель открытого экрана — тремя путями, потому что ни один не отвечает
 * всегда.
 *
 * В `env.config` в момент первой отрисовки модели может не быть вовсе, а
 * служба действий знает её и тогда. Проверка по одному источнику молча не
 * срабатывала: признак возвращал «нет», ошибки не было, и правило просто
 * не применялось.
 */
export function coopModelOf(component) {
    return (
        component.env?.searchModel?.resModel ||
        component.coopActionService?.currentController?.action?.res_model ||
        component.props?.resModel ||
        component.env?.config?.resModel ||
        null
    );
}
