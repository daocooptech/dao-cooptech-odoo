/**
 * Один запрос на запуск оболочки вместо пяти.
 *
 * Боковое меню, колокольчик, переключатель «действую от имени», признак
 * управляющего и счётчик отзывов — пять частей оболочки, и каждая
 * спрашивала сервер сама. Все пять уходят до того, как начнёт грузиться
 * раздел, и занимают те же соединения: браузер держит их к одному узлу
 * шесть штук. На боевой установке это полторы секунды впереди
 * содержимого при паре килобайт ответа.
 *
 * Служба спрашивает один раз и раздаёт обещание: кто бы ни спросил
 * вторым, он получит тот же ответ, а не второй запрос. `refresh()` —
 * для тех, кому нужно свежее (колокольчик опрашивает раз в минуту).
 */
import { registry } from "@web/core/registry";

export const coopBootService = {
    dependencies: ["orm"],
    start(env, { orm }) {
        let promise = null;

        function load() {
            if (!promise) {
                promise = orm.call("coop.shell", "boot", []).catch((error) => {
                    // Сорвалось — отпускаем обещание, чтобы следующий
                    // спросивший попробовал заново, а не получил навсегда
                    // застрявшую ошибку.
                    promise = null;
                    throw error;
                });
            }
            return promise;
        }

        return {
            /** Данные запуска; второй и последующие вызовы бесплатны. */
            get: load,
            /** Спросить заново — например, после действия, меняющего счётчики. */
            refresh() {
                promise = null;
                return load();
            },
        };
    },
};

registry.category("services").add("coopBoot", coopBootService);
