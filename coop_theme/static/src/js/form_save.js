/** @odoo-module **/

import { patch } from "@web/core/utils/patch";
import { FormController } from "@web/views/form/form_controller";
import { coopIsPlatformModel } from "@coop_theme/js/platform_page";

/**
 * Сохранение — рядом с тем, что тронули, а не в шапке.
 *
 * Решение владельца 16 сентября 2026 (332): страничные кнопки сохранения
 * убрать. После перевода полей на правку по месту (решение 344) они и не
 * появлялись — пока человек не трогал то, что правится иначе: встроенный
 * список (вклады, потребности и доли проекта, зоны склада, условия
 * объявления мощностей, ступени программы) или изображение. Такая правка
 * держится в памяти записи и без страничного сохранения пропадает.
 *
 * Замер 21 сентября: списков таких шесть, и правит их не администратор в
 * редком случае, а обычный участник на своих записях — из трёх
 * проверенных складов запись разрешена на двух, из трёх объявлений
 * мощностей на двух. Значит тупик был бы настоящий, а не теоретический.
 *
 * Владелец 21 сентября выбрал из трёх путей третий: «давай третий вариант
 * тогда» — одна кнопка на странице, но рядом со списком, а не в шапке.
 *
 * Почему не «научить списки сохранять себя сразу». У `X2ManyField` в
 * Odoo 19 нет открытого крючка на завершение правки строки: `saveRecord`
 * и `removeRecord` замкнуты внутри `setup`, а строка фиксируется через
 * `list.leaveEditMode()` внутри общего отрисовщика списков — того же,
 * который рисует обычные каталоги. Ради шести форм перекрывать его
 * значит взять на себя починку после каждого обновления движка.
 *
 * Почему одна полоса на страницу, а не по одной под каждым списком.
 * Страницу делает изменённой не только список: изображение, а на части
 * экранов и поля, до которых правка по месту ещё не дошла. Полоса под
 * списком оставила бы эти случаи без сохранения вовсе — тупик хуже
 * кнопки в шапке. Одна полоса ловит любое изменение, откуда бы оно ни
 * пришло.
 */
patch(FormController.prototype, {
    /** Платформенная ли это страница записи. */
    get coopIsPlatformPage() {
        try {
            return coopIsPlatformModel(
                this.props?.resModel || this.model?.root?.resModel
            );
        } catch (ошибка) {
            console.warn("[форма] не удалось решить, чья это страница:", ошибка);
            return false;
        }
    },

    /**
     * Есть ли что сохранять.
     *
     * Всё вычисление обёрнуто: getter зовётся на каждой отрисовке формы, а
     * форма — это каждая карточка платформы. Брошенное отсюда исключение
     * означало бы не «полоса не нарисовалась», а сорванную отрисовку всей
     * страницы. Не сосчиталось — значит полосы нет, и остаётся обычное
     * поведение движка.
     */
    get coopHasChanges() {
        try {
            const root = this.model?.root;
            return Boolean(root && (root.dirty || root.isNew));
        } catch (ошибка) {
            console.warn("[форма] не удалось решить, есть ли правки:", ошибка);
            return false;
        }
    },
});
