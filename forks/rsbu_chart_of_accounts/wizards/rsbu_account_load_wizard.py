KIND_MAP = {'A': 'active', 'P': 'passive', 'AP': 'active_passive', 'OB': 'off_balance'}
SUBCONTO_FIELD = {'p': 'subconto_partner', 'pr': 'subconto_product',
                  'u': 'subconto_user', 'e': 'subconto_employee'}


class RsbuAccountLoadWizard(models.TransientModel):
    """Визард загрузки типового плана счетов 94н для компании."""
    _name = 'rsbu.account.load.wizard'
    _description = 'РСБУ — Загрузка типового плана счетов'

    company_id = fields.Many2one(
        'res.company', string='Компания', required=True,
        default=lambda self: self.env.company,
    )
    overwrite = fields.Boolean(
        string='Не создавать существующие',
        default=True,
        help='Пропускать счета, код которых уже есть у компании.',
    )

    def _subconto_vals(self, subconto):
        vals = {}
        for key in subconto:
            vals[SUBCONTO_FIELD[key]] = True
        return vals

    def action_load(self):
        self.ensure_one()
        Account = self.env['rsbu.account']
        company = self.company_id
        existing = {a.code: a for a in Account.with_context(
            active_test=False).search([('company_id', '=', company.id)])}

        # 1) Синтетические счета.
        for code, name, kind, subconto in CHART_94N:
            if code in existing:
                continue
            vals = {
                'code': code, 'name': name,
                'account_kind': KIND_MAP[kind],
                'company_id': company.id,
            }
            vals.update(self._subconto_vals(subconto))
            existing[code] = Account.create(vals)

        # 2) Субсчета (с привязкой к родителю).
        for code, name, kind, subconto, parent_code in SUBACCOUNTS_94N:
            if code in existing:
                continue
            parent = existing.get(parent_code)
            vals = {
                'code': code, 'name': name,
                'account_kind': KIND_MAP[kind],
                'company_id': company.id,
                'parent_id': parent.id if parent else False,
            }
            vals.update(self._subconto_vals(subconto))
            existing[code] = Account.create(vals)

        return {
            'type': 'ir.actions.act_window',
            'name': _('План счетов РСБУ'),
            'res_model': 'rsbu.account',
            'view_mode': 'list,form',
            'domain': [('company_id', '=', company.id)],
        }
