#!/usr/bin/env bash
# Прогреть пакеты стилей и скриптов.
#
#   bash warmup.sh [адрес]
#
# Odoo собирает пакеты при первом обращении и складывает результат в
# базу. Сборка стоит секунд десять, и без прогрева их платит тот, кто
# зашёл первым — на пустой белой странице. Поэтому после каждой сборки
# ассетов (обновление модулей, сброс пакетов) их запрашивают заранее, и
# делает это не человек, а сценарий.
#
# Запрашиваем именно те адреса, что стоят в разметке: пакет собирается
# на обращение к нему, а не к странице, которая на него ссылается.
#
# И обращаемся не по «любой версии», а по нарочно несуществующей.
#
# `/web/assets/any/…` означает «отдай, что лежит»: движок ищет любое
# вложение с подходящим именем и отдаёт его, не проверяя, отвечает ли оно
# нынешнему коду. После обновления модулей там лежит прошлая сборка —
# прогрев отрабатывал за сотые доли секунды, прогревал вчерашний пакет, а
# первый зашедший всё равно платил за сборку. Замерено 16 сентября 2026:
# 21,4 с на скрипты и 6,2 с на стили у первого запроса после выкатки.
#
# С несуществующей версией вложение не находится, и движок отвечает
# перенаправлением на канонический адрес нынешней сборки, попутно её
# собирая. Поэтому `-L`: идём по перенаправлению и печатаем, какой адрес
# в итоге прогрет — по нему видно версию.
set -u
BASE="${1:-http://127.0.0.1:8069}"
started=$(date +%s)

# Пакеты бэкенда — отдельным списком, и вот почему. Сценарий собирал
# адреса со страниц, но /odoo без входа отдаёт форму логина, а значит
# самый тяжёлый пакет — web.assets_web, семь мегабайт скриптов — не
# прогревался никогда. В логе его сборка занимает двенадцать секунд,
# и платил их первый вошедший участник, глядя на пустую страницу.
# Сами адреса ассетов вход не требуют, поэтому запросить их можно прямо.
# `warm` — заведомо несуществующая версия, см. объяснение выше.
#
# Имена переменных латиницей: в именах переменных оболочки кириллица
# недопустима, и `ответ=...` не присваивание, а команда, которой нет.
for asset in /web/assets/warm/web.assets_web.min.js              /web/assets/warm/web.assets_web.min.css              /web/assets/warm/web.assets_web_print.min.css; do
    answer=$(curl -sL -o /dev/null -w '%{time_total} %{url_effective}'         --max-time 300 "$BASE$asset" || echo '- -')
    seconds=${answer%% *}
    final=${answer##* }
    version=$(printf '%s' "$final" | sed 's#.*/web/assets/##; s#/.*##')
    printf '  %-40s %8s c  %s
' "$(basename "$asset")" "$seconds" "$version"
done

for page in /web/login /odoo; do
    html=$(curl -s --max-time 120 "$BASE$page" || true)
    printf '%s' "$html" | grep -oE '/web/assets/[^"]+\.(js|css)' | sort -u \
    | while read -r asset; do
        seconds=$(curl -s -o /dev/null -w '%{time_total}' --max-time 300 \
            "$BASE$asset" || echo '—')
        printf '  %-56s %s с\n' "$(basename "$asset")" "$seconds"
    done
done

echo "Прогрев занял $(( $(date +%s) - started )) с"
