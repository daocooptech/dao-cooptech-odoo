# Порядок меню и двойники (решение 493) — после каждого обновления модулей.
#
# Модули при обновлении перечитывают свои меню из XML: пункты, привязанные
# к штатным «Настройкам», «Управлению складом» и «Событиям», возвращаются
# под скрытый корень и пропадают. `coop.menu.order.apply` переносит их в
# наши разделы снова. Запуск: odoo-bin shell ... < deploy/menu_order.py
if 'coop.menu.order' in env:
    env['coop.menu.order'].apply()
    env.cr.commit()
    print('Порядок меню применён')
