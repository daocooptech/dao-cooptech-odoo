# -*- coding: utf-8 -*-
from odoo import _, api, fields, models
from odoo.exceptions import ValidationError


class ResPartner(models.Model):
    _inherit = 'res.partner'

    # Решение 513 (владелец 26.10.2026: «Выбирает каждый узел»). Агент —
    # кооператив, и штраф за неудержание (20 %, п. 1 ст. 123 НК) платит
    # он, поэтому и выбор его. По умолчанию — позиция Минфина (письмо
    # 30.10.2020 № 03-04-05/94934): вся стоимость пая — доход.
    coop_ndfl_share_base = fields.Selection([
        ('full', 'Со всей суммы пая'),
        ('excess', 'Только сверх внесённого'),
    ], string='НДФЛ при возврате пая', default='full', required=True,
        help='Со всей суммы — как велит Минфин, кооператив защищён его '
             'письмом. Только сверх внесённого — пайщик получает больше, '
             'но кооператив рискует штрафом 20 % от недоудержанного и пени.')

    # Ставка по соглашению об избежании двойного налогообложения (К1).
    # Пусто — нерезиденту 30 % (п. 3 ст. 224 НК).
    coop_tax_treaty_rate = fields.Float(
        string='Ставка НДФЛ по соглашению, %', digits=(5, 2),
        help='Для налогового нерезидента из страны, с которой у России '
             'действует соглашение об избежании двойного налогообложения: '
             'ставка из соглашения при подтверждённом резидентстве. Пусто — '
             '30 %.')

    # Решение 517 (владелец 26.10.2026: «Выбирает узел»). П. 2 ст. 24
    # 3085-1 ограничивает выплаты 20 % «от доходов», не определяя их. По
    # умолчанию — осторожная база: чистая прибыль.
    coop_payout_limit_base = fields.Selection([
        ('net_profit', 'Чистая прибыль предпринимательской части'),
        ('income_after_taxes', 'Доходы после обязательных платежей'),
    ], string='База лимита кооперативных выплат', default='net_profit', required=True,
        help='От чего считать потолок 20 %. Чистая прибыль — потолок ниже, '
             'оспорить решение собрания труднее. Доходы после обязательных '
             'платежей — буквально по закону, потолок выше, но выплатить '
             'больше нераспределённой прибыли после фондов всё равно нельзя.')

    # Решение 514 (владелец 26.10.2026: «Каждый кооператив решает сам»).
    # Членов артели нет в п. 1 ст. 5 125-ФЗ, но ст. 19 41-ФЗ даёт им
    # социальное страхование наравне с наёмными.
    coop_injury_insurance = fields.Boolean(
        string='Взносы на травматизм с выплат членам',
        help='Платить ли взносы на страхование от несчастных случаев с '
             'выплат членам за трудовое участие. Не платя, кооператив '
             'рискует недоимкой и пенями, если СФР признает это '
             'страхование обязательным.')
    coop_injury_rate = fields.Float(
        string='Тариф по классу риска, %', digits=(5, 2), default=0.2,
        help='От 0,2 до 8,5 % — по классу профессионального риска '
             'основного вида деятельности.')
    coop_tax_sme = fields.Boolean(
        string='МСП из перечня — пониженный тариф взносов',
        help='П. 2.4 ст. 427 НК: 15 % с части выплат сверх 1,5 МРОТ в месяц, '
             'если кооператив в реестре МСП и основной вид деятельности — '
             'из перечня.')

    @api.constrains('coop_injury_insurance', 'coop_injury_rate')
    def _check_coop_injury_rate(self):
        for partner in self.filtered('coop_injury_insurance'):
            if not 0.2 <= partner.coop_injury_rate <= 8.5:
                raise ValidationError(_(
                    'Тариф на травматизм — от 0,2 до 8,5 % по классу '
                    'профессионального риска.'))
