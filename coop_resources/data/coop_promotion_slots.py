# -*- coding: utf-8 -*-
"""Места в выдаче: цена и охват по строке и странице.

Продвижение покупается местом (решение владельца от 2026-09-01). Цена не
назначена волей, а выведена из охвата: место, до которого доходит вдвое
меньше смотрящих, и стоить должно вдвое меньше. Иначе прайс-лист
приходится защищать в каждом разговоре, а так он объясняется одной
строкой.

Затухание внимания взято по двум осям:

- **по строкам внутри блока** — первая строка видна всем, кто открыл
  страницу, дальше внимание падает примерно на четверть на строку. Это
  наблюдение старое и устойчивое: в любой выдаче первая позиция собирает
  кратно больше, чем четвёртая;
- **по страницам** — до второй страницы доходит около трети, до третьей
  вдвое меньше, и так далее. Пятая страница — предел, за которым
  продвигать бессмысленно, поэтому дальше места не продаются.

Числа — доли, а не проценты кликов: измерять пока нечего, а порядок
величин важнее точности. Как только появится статистика просмотров,
таблица пересчитается из неё, и цена поедет за охватом сама.
"""
import logging

_logger = logging.getLogger(__name__)

SLOTS_PER_PAGE = 4
PROMOTED_PAGES = 5

# Доля тех, кто вообще доходит до страницы.
PAGE_REACH = {1: 1.0, 2: 0.34, 3: 0.17, 4: 0.10, 5: 0.06}

# Доля внимания на строке внутри платного блока.
POSITION_REACH = {1: 1.0, 2: 0.72, 3: 0.55, 4: 0.42}

# Цена первой строки первой страницы, в токенах за сутки. Остальные
# считаются от неё пропорционально охвату, с округлением вверх до целого:
# место дешевле одного токена в сутки не продаётся, иначе продвижение
# перестаёт быть выбором и становится фоном.
TOP_PRICE_PER_DAY = 24


def load_promotion_slots(env):
    Slot = env['coop.promotion.slot'].sudo()
    created = updated = 0

    for page in range(1, PROMOTED_PAGES + 1):
        for position in range(1, SLOTS_PER_PAGE + 1):
            reach = PAGE_REACH[page] * POSITION_REACH[position]
            price = max(1, round(TOP_PRICE_PER_DAY * reach))
            values = {
                'page': page,
                'position': position,
                'price_per_day': price,
                'reach_share': round(reach * 100, 1),
            }
            slot = Slot.search([('page', '=', page),
                               ('position', '=', position)], limit=1)
            if slot:
                slot.write(values)
                updated += 1
            else:
                Slot.create(values)
                created += 1

    _logger.info('Места в выдаче: создано %s, обновлено %s', created, updated)
    return True
