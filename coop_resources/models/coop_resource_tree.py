# Труд и деньги, попавшие в разделы вещей или оставшиеся без раздела.
LABOUR_398 = [
    (('переезд', 'перевоз', 'развозчик', 'водитель'), 'Перевозка и доставка'),
]
FINANCE_398 = [
    (('грант', 'заём', 'займ', 'инвестиц', 'кредит', 'пожертвован',
      'депозит'), 'Финансирование'),
]


def _ensure_path(Category, path):
    """Цепочка категорий по пути; существующая с тем же именем переезжает."""
    parent = None
    for depth, name in enumerate(path):
        record = _find(Category, name, parent)
        if not record and depth:
            # Есть где-то ещё — переносим на место, не заводя двойника.
            record = Category.search([('name', '=', name)], limit=1)
            if record:
                record.parent_id = parent.id
        if not record:
            record = Category.create(
                {'name': name, 'parent_id': parent.id if parent else False})
        parent = record
    return parent


def _title(name):
    """Название без хвоста «— проект — город»: в хвосте «Екатеринбург»
    даёт «катер», а «Цех переработки шерсти» — цех, и объявление уезжало
    в водный транспорт и производственные помещения."""
    return (name or '').split(' — ')[0].lower()


def _match(rules, name):
    low = _title(name)
    for words, target in rules:
        if any(w in low for w in words):
            return target
    return None


def rebuild_398(env):
    """Дерево задачи 398 поверх девяти разделов. Идемпотентна."""
    Category = env['coop.resource.category'].sudo().with_context(
        tracking_disable=True)
    Resource = env['coop.resource'].sudo().with_context(
        tracking_disable=True)
    Assignment = env['coop.attribute.assignment'].sudo() \
        if 'coop.attribute.assignment' in env else None

    for old, new in RENAMES_398:
        for record in Category.search([('name', '=', old)]):
            twin = Category.search([('name', '=', new),
                                    ('id', '!=', record.id)], limit=1)
            if not twin:
                record.name = new
            elif Assignment is not None:
                _merge(Category, Resource, Assignment, record, twin)

    by_name = {}
    for path in TREE_398:
        by_name[path[-1]] = _ensure_path(Category, path)

    def target(name):
        if name not in by_name:
            by_name[name] = _find(Category, name, any_parent=True)
        return by_name[name]

    services = _find(Category, 'Услуги и финансы', None)
    service_ids = Category.search(
        [('id', 'child_of', services.id)]).ids if services else []
    split_ids = Category.search([('name', 'in', list(SPLIT_398))]).ids
    moved = 0
    for resource in Resource.search(
            ['|', ('category_id', '=', False),
             ('category_id', 'not in', service_ids)]):
        kind = resource.resource_type
        current = resource.category_id
        name = None
        if kind == 'labour':
            name = _match(LABOUR_398, resource.name) or 'Работа и подряд'
        elif kind == 'financial':
            name = _match(FINANCE_398, resource.name) or \
                'Платежи и обязательные расходы'
        elif not current or current.id in split_ids:
            name = _match(RULES_398, resource.name)
            # «Сдам сварочный аппарат» — прокат инструмента, не станок.
            low = _title(resource.name)
            if name in ('Станки по дереву и металлу', 'Для стройки') and \
                    any(w in low for w in RENT):
                name = 'Инструмент в прокат'
        if not name:
            continue
        category = target(name)
        if category and category != current:
            resource.category_id = category.id
            moved += 1

    # Расформирование: остаток — в целевую категорию или в родителя.
    if Assignment is not None:
        for name, into in DISSOLVE_398:
            for record in Category.search([('name', '=', name)]):
                dest = target(into) if into else record.parent_id
                if dest:
                    _merge(Category, Resource, Assignment, record, dest)
    _logger.info('Дерево разделов (398): перенесено записей %s', moved)
    return moved
