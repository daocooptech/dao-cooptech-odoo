def _find(Category, name, parent=None, any_parent=False):
    domain = [('name', '=', name)]
    if not any_parent:
        domain.append(('parent_id', '=', parent.id if parent else False))
    return Category.search(domain, limit=1)


def _merge(Category, Resource, Assignment, source, target):
    """Слить дубль `source` в `target`: записи, подкатегории, привязки."""
    Resource.search([('category_id', '=', source.id)]).write(
        {'category_id': target.id})
    source.child_ids.write({'parent_id': target.id})
    have = set(Assignment.search(
        [('category_id', '=', target.id)]).mapped('attribute_id').ids)
    for assignment in Assignment.search([('category_id', '=', source.id)]):
        if assignment.attribute_id.id in have:
            assignment.unlink()
        else:
            assignment.category_id = target.id
    source.unlink()


def rebuild_category_tree(env):
    """Привести категории материальных ресурсов к девяти разделам."""
    Category = env['coop.resource.category'].sudo().with_context(
        tracking_disable=True)
    Resource = env['coop.resource'].sudo().with_context(
        tracking_disable=True)
    Assignment = env['coop.attribute.assignment'].sudo() \
        if 'coop.attribute.assignment' in env else None

    def root(name):
        return _find(Category, name, None)

    def ensure(name, parent_name, copy_from=None):
        parent = root(parent_name) if parent_name else None
        if parent_name and not parent:
            parent = _find(Category, parent_name, any_parent=True)
        record = _find(Category, name, parent)
        if not record:
            record = Category.create(
                {'name': name, 'parent_id': parent.id if parent else False})
            if Assignment is not None and copy_from:
                source = _find(Category, copy_from, any_parent=True)
                for item in Assignment.search(
                        [('category_id', '=', source.id)]):
                    item.copy({'category_id': record.id})
        return record

    # 1. Переименование и переезд прежних категорий (id сохраняются).
    for old, new, parent_name in RENAMES:
        parent = (ensure(parent_name, None) if parent_name else None)
        old_rec = Category.search([('name', '=', old)])
        # Прежняя категория уже в новом месте — ничего не делаем; старый
        # «Услуги» не путать с новым «Деловые услуги» (другое имя).
        for record in old_rec:
            if old == new and (record.parent_id.id or False) == (
                    parent.id if parent else False):
                continue
            exists = _find(Category, new, parent)
            if exists and exists != record:
                if Assignment is not None:
                    _merge(Category, Resource, Assignment, record, exists)
                continue
            record.write({'name': new,
                          'parent_id': parent.id if parent else False})
    # 2. Новые категории.
    for name, parent_name, copy_from in NEW:
        ensure(name, parent_name, copy_from)

    # 3. Перенос записей по названию.
    moved = 0
    for rule in RULES:
        sources, words, target_name = rule[0], rule[1], rule[2]
        also = rule[3] if len(rule) > 3 else None
        skip = rule[4] if len(rule) > 4 else ()
        target = _find(Category, target_name, any_parent=True)
        domain = [('resource_type', '=', 'material'),
                  ('category_id', '!=', target.id)]
        if sources:
            cats = Category.search([('name', 'in', list(sources))])
            domain.append(('category_id', 'in', cats.ids))
        else:
            domain.append(('category_id', '!=', False))
        for resource in Resource.search(domain):
            low = (resource.name or '').lower()
            if any(w in low for w in words) and (
                    also is None or any(a in low for a in also)) and not any(
                    s in low for s in skip):
                resource.category_id = target.id
                moved += 1
    moved += rebuild_398(env)
    _logger.info('Дерево разделов ресурсов: перенесено записей %s', moved)
    return moved


