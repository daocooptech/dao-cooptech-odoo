"""«Оборудование» становится материальным ресурсом (решение 632).

Владелец 28.10.2026: виды ресурсов — материальные, нематериальные,
трудовые, финансовые; «Оборудование» вливается в материальные. До этого
у каталога было четыре вида с отдельным `equipment`, и половина объявлений
каталога стояла в нём.

Что меняем: сам вид у записей. Рубрики и способы передачи не трогаем — они
и так про вещи, а не про вид. Нематериальные сюда не переводим: они живут
отдельным модулем.
"""
import logging

from odoo import api, SUPERUSER_ID

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    if not version:
        return
    cr.execute("""
        UPDATE coop_resource
           SET resource_type = 'material'
         WHERE resource_type = 'equipment'
    """)
    _logger.info('Виды ресурсов: «оборудование» переведено в материальные, '
                 'записей %s', cr.rowcount)
