WORK_START = ('ищу ', 'нужен ', 'нужна ')


def rubric_for(name):
    low = (name or '').lower()
    if low.startswith(WORK_NAMES):
        return W
    for words, leaf in RUBRICS:
        if any(re.search(r'(?<!\w)' + re.escape(w), low) for w in words):
            return leaf
    return W if low.startswith(WORK_START) else None


def load_rubrics(env):
    Category = env['coop.resource.category'].sudo()
    Resource = env['coop.resource'].sudo().with_context(
        active_test=False, tracking_disable=True, mail_notrack=True)
    leaves = {}
    placed, unknown = 0, set()
    # В корне «Сырья» набора нет: корень — не раздел, а папка разделов.
    for resource in Resource.search(DEMO + [
            '|', ('category_id', '=', False),
            ('category_id.complete_name', '=', S[:-3])]):
        full = rubric_for(resource.name)
        if full and full not in leaves:
            leaves[full] = Category.search([('complete_name', '=', full)], limit=1)
        if full and leaves[full]:
            resource.category_id = leaves[full]
            placed += 1
        else:
            unknown.add(resource.name)
    tidy_catalogs.move_misplaced(env)
    _logger.info('483: рубрика поставлена у %s, не нашлось: %s',
                 placed, sorted(unknown)[:10])
    return placed


