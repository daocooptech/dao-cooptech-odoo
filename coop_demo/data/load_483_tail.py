def unit_for(branch, name, current):
    """Единица цены продажи; у штучного, недвижимости и работ её нет."""
    low = (name or '').lower()
    if branch.endswith('Земельные участки'):
        return 'сотка' if current == 'сотка' else False
    if not (branch + ' / ').startswith(BULK_ROOTS) or low.startswith(NOT_GOODS):
        return False
    allowed = ALLOWED.get(branch, ())
    # «Коробка „Мини“ · зелень и овощи» — подписка, цена за неделю.
    if current == 'нед.' and current in allowed:
        return current
    for words, unit in UNIT_BY_WORD:
        if any(re.search(r'(?<!\w)' + re.escape(w), low) for w in words):
            return current if current in allowed and unit not in ONE_UNIT else unit
    return current if current in allowed else False


# Дороже этого за малую меру — значит, продают крупной: «4 500 ₽ / десяток».
DEAR = {'десяток': 250, 'л': 250, 'банка': 800, 'кг': 1500}
PACKS = (('сыр из', 'головка'), ('мёд', 'банка 3 л'), ('картофел', 'мешок'), ('шерст', 'мешок'),
         ('молок', 'фляга'), ('варень', 'набор'), ('соленья', 'набор'))


def _pack(unit, name, price):
    if unit not in DEAR or price <= DEAR[unit]:
        return unit
    low = (name or '').lower()
    return next((pack for word, pack in PACKS if word in low), 'коробка')


def _batch(price):
    """Наименьшая партия по цене: сто кирпичей, но не сто бочек мёда."""
    for limit, qty in ((150, 100), (600, 50), (2000, 20), (6000, 10), (20000, 5)):
        if price <= limit:
            return qty
    return 0


RENT_UNITS = ('сутки', 'месяц', 'мес', 'час', 'нед.', 'смена', 'га/сезон')
STEPS = (('bulk', 2, 0.93), ('bulk2', 4, 0.88), ('bulk3', 8, 0.82))


def _money(value):
    return float(round(value) if value < 1000 else round(value / 10.0) * 10)


def fix_units(env):
    Term = env['coop.resource.term'].sudo().with_context(
        tracking_disable=True, mail_notrack=True)
    fixed = 0
    for term in Term.search([('code', 'in', ('sale', 'installment', 'leasing'))]):
        if term.write_uid.id > 2:
            continue                    # правил человек — его слово
        resource = term.resource_id
        branch = resource.category_id.complete_name or ''
        vals = {}
        unit = _pack(unit_for(branch, resource.name, term.price_unit_label),
                     resource.name, term.price)
        if resource.listing_type != 'offer' and unit != 'сотка':
            unit = False                # у спроса сумма — сколько готов отдать
        if (term.price_unit_label or False) != unit:
            vals['price_unit_label'] = unit
        if term.code == 'sale' and (term.min_qty or term.bulk_qty or term.bulk2_qty
                                    or term.bulk3_qty):
            batch = _batch(term.price) if unit and unit not in ('нед.', 'сотка') \
                and resource.listing_type == 'offer' else 0
            if not batch:
                for field in ['min_qty'] + ['%s_%s' % (s[0], k) for s in STEPS
                                            for k in ('qty', 'price')]:
                    if term[field]:
                        vals[field] = 0
            else:
                batch = min(batch, int(term.min_qty or batch))
                if term.min_qty != batch:
                    vals['min_qty'] = batch
                for prefix, times, rate in STEPS:
                    if not term['%s_qty' % prefix]:
                        continue
                    want = {'%s_qty' % prefix: float(batch * times),
                            '%s_price' % prefix: _money(term.price * rate)}
                    vals.update({k: v for k, v in want.items() if term[k] != v})
        if vals:
            term.write(vals)
            fixed += 1
        # Единица цены на карточке — та же, что у её способа; посуточную
        # и помесячную (цена аренды) не трогаем.
        priced = resource.term_ids.filtered(
            lambda t: t.code != 'free' and t.price).sorted('sequence')[:1]
        if priced == term and (resource.price_unit_label or False) != unit and                 (resource.price_unit_label or '') not in RENT_UNITS:
            resource.with_context(coop_no_price_sync=True).price_unit_label = unit
    _logger.info('483: единица и опт поправлены у %s условий', fixed)
    return fixed


# «Крепёж и метизы, 1534 кг» — сумма за всё, а читалось «185 000 ₽/кг»;
# у работ так же: «Инженер-технолог, 14 недель — 505 000 ₽/неделя».
def is_total(name, unit):
    stem = {'месяц': 'мес', 'неделя': 'недел', 'нед.': 'недел', 'смена': 'смен',
            'сутки': 'сут', 'тонна': 'тонн'}.get(unit, unit.rstrip('.'))
    # Основа слова («недел») принимает окончание, сокращение («м») — нет.
    tail = r'\w*' if len(stem) > 2 else r'(?!\w)'
    return bool(re.search(r'\d\s+' + re.escape(stem) + tail, (name or '').lower()))


def fix_totals(env):
    fixed = 0
    for resource in env['coop.resource'].sudo().with_context(
            active_test=False, tracking_disable=True, mail_notrack=True,
            coop_no_price_sync=True).search(DEMO + [('price_unit_label', '!=', False)]):
        unit = resource.price_unit_label
        if not unit or resource.write_uid.id > 2 or not is_total(resource.name, unit):
            continue
        resource.price_unit_label = False
        resource.term_ids.filtered(
            lambda t: t.price_unit_label == unit).write({'price_unit_label': False})
        fixed += 1
    _logger.info('483: цена за всю партию — без «за кг» у %s', fixed)
    return fixed


