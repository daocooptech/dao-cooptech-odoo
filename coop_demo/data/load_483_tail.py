def load_services(env):
    Offer = env['coop.skill.offer'].sudo().with_context(
        active_test=False, tracking_disable=True, mail_notrack=True)
    Partner = env['res.partner'].sudo()
    specs = {s.name: s for s in env['coop.specialization'].sudo().search([])}
    made = 0
    for index, (name, spec, org, rate, period, text) in enumerate(SERVICES):
        key = 'service483#%s' % index
        if Offer.search_count([('import_key', '=', key)]):
            continue
        partner = Partner.search([('name', '=', org), ('is_company', '=', True)], limit=1)
        if not partner or spec not in specs:
            _logger.info('483: услуга «%s» — нет организации или специализации', name)
            continue
        city = partner.city if partner.city and partner.city != 'Удалённо' else 'Москва'
        # Снимок — у предложения той же специализации, чтобы не было пусто.
        sample = next((o for o in Offer.search(
            [('coop_specialization_id', '=', specs[spec].id)], order='id') if o.image_1920),
            Offer.browse())
        Offer.create({
            'import_key': key, 'name': name, 'description': '<p>%s</p>' % text,
            'partner_id': partner.id, 'coop_specialization_id': specs[spec].id,
            'skill_ids': [Command.set(sample.skill_ids.ids)], 'city': city,
            'ready_to_travel': index % 3 != 0, 'experience_months': 24 + (index * 17) % 130,
            'rate': rate, 'rate_kind': 'from' if rate >= 10000 else 'exact',
            'rate_period': period, 'employment': 'full' if period == 'month' else 'once',
            'work_schedule': 'full_day' if index % 2 else 'flexible',
            'image_1920': sample.image_1920 or False,
            'state': 'draft' if index % 18 == 17 else 'published',
        })
        made += 1
    _logger.info('483: услуг организаций добавлено %s', made)
    return made


def fill_bare(env):
    """Объявления «…, с доставкой» по слову уезжали в перевозку, а `tidy_names`
    возвращал их в свою рубрику уже после наборов — с пустым набором."""
    env.flush_all()
    env.cr.execute("""
        SELECT count(*) FROM coop_resource WHERE category_id IS NOT NULL
           AND (attrs IS NULL OR attrs::text IN ('{}', '[]', 'null'))""")
    bare = env.cr.fetchone()[0]
    if bare:
        from . import load_483, load_attributes, load_branch_attributes
        load_attributes.load_attributes(env)
        load_branch_attributes.load_branch_attributes(env)
        load_483.load_483(env)
    _logger.info('483: без характеристик после имён было %s', bare)
    return bare


def load_tail(env):
    tidy_catalogs.drop_repeats(env)
    tidy_catalogs.move_misplaced(env)
    fill_bare(env)
    tidy_catalogs.fix_prices(env)
    return fix_units(env), fix_totals(env), fix_vacancies(env)
