DAY = re.compile(r'на (не)?полный день')
WORDS = {'part': ('на неполный день', 'подработка', 'неполная смена'),
         'project': ('на время проекта', 'проектная работа', 'по договору подряда'),
         'volunteer': ('в свободное время', 'по выходным', 'разовая помощь')}


def fix_vacancies(env):
    Vacancy = env['coop.vacancy'].sudo().with_context(
        active_test=False, tracking_disable=True, mail_notrack=True)
    records = Vacancy.search([], order='id')
    taken = set(records.mapped('name'))
    fixed = 0
    for record in records:
        words = WORDS.get(record.employment)
        found = DAY.search(record.name or '')
        if not (words and found) or found.group(0) == words[0]:
            continue
        for word in words:
            name = DAY.sub(word, record.name)
            if name not in taken:
                record.name = name
                taken.add(name)
                fixed += 1
                break
    _logger.info('483: занятость в названии поправлена у %s вакансий', fixed)
    return fixed


