"""Снимок каждой вакансии, у которой его нет.

Проверено 15 сентября 2026: у Дашкевича — главного демонстрационного
участника — в полке «Вакансии» четырнадцать плиток и ни одного снимка.
На всю платформу снимок был у 145 вакансий из 392.

Каталог вакансий снимки ставит: в `load_vacancies` у каждой записи либо
фотография по названию, либо знак по роду занятий. А вакансии под
трудовые потребности проектов заводятся отдельно, в
`load_project_needs`, и поля снимка там не было вовсе. Пустое место в
плитке читается как незагрузившаяся картинка — не как «фотографии нет».

Отдельным шагом, а не правкой места создания, по двум причинам. Первая:
так чинятся и уже заведённые записи, а не только будущие. Вторая: шаг
идёт последним и подбирает снимок всему, что завели до него, — кто бы
ни завёл и когда бы ни появился следующий загрузчик вакансий.

Правило подбора то же, что и в каталоге ресурсов: сначала фотография по
названию, а если предмет не опознан — знак по роду занятий. Второго
набора правил не заводим: он разошёлся бы с первым при первой правке.
"""
import logging

from . import emblems, photos

_logger = logging.getLogger(__name__)


def load(env):
    Vacancy = env['coop.vacancy'].sudo()
    без_снимка = Vacancy.search([('image_1920', '=', False)])
    if not без_снимка:
        _logger.info('Снимки вакансий: все на месте')
        return 0

    фотографией = 0
    знаком = 0
    for вакансия in без_снимка:
        # Savepoint на каждую: PostgreSQL обрывает транзакцию на первой
        # ошибке, и без него одна негодная запись тихо отменила бы все
        # остальные снимки этого прогона.
        with env.cr.savepoint():
            снимок = photos.photo_for(вакансия.name)
            if снимок:
                вакансия.write({'image_1920': снимок})
                фотографией += 1
                continue
            род = вакансия.name
            специализация = getattr(вакансия, 'coop_specialization_id', None)
            if специализация:
                род = специализация.display_name or род
            вакансия.write({
                'image_1920': emblems.emblem(вакансия.name, род),
            })
            знаком += 1

    _logger.info('Снимки вакансий: %s фотографией, %s знаком',
                 фотографией, знаком)
    return фотографией + знаком
