def load_courses(env, login='dashkevich'):
    Param = env['ir.config_parameter'].sudo()
    if Param.get_param(PARAM) == VERSION:
        return 0
    if 'slide.channel' not in env or 'coop_topic' not in env['slide.channel']._fields:
        return 0
    # Наполнение не должно писать людям. Прохождение уроков начисляет карму,
    # а новый ранг — письмо «Новый ранг»; движок сам не шлёт его в режиме
    # установки (`install_mode`, gamification/res_users.py) — им и
    # пользуемся. Письмо «Вы завершили курс» шлёт шаблон курса: на время
    # наполнения его у курса нет, после — ставится штатный, и настоящие
    # ученики письмо получат. Прогон на копии боевой 26.09 без этого завёл
    # полторы тысячи писем в очередь, а без шаблона публикации — ещё
    # шестьсот уведомлений подписчикам о новых уроках.
    env = env(context=dict(env.context, install_mode=True, mail_notrack=True,
                           tracking_disable=True, mail_create_nolog=True))
    completed_template = env.ref('website_slides.mail_template_channel_completed',
                                 raise_if_not_found=False)
    # То же с письмом подписчикам «опубликован новый урок» — шаблон курса.
    publish_template = env.ref('website_slides.slide_template_published',
                               raise_if_not_found=False)
    Channel = env['slide.channel'].sudo().with_context(mail_create_nolog=True, tracking_disable=True,
                                                       mail_notrack=True, mail_create_nosubscribe=True)
    Slide = env['slide.slide'].sudo().with_context(mail_create_nolog=True, tracking_disable=True)
    users = env['res.users'].sudo().search([
        ('share', '=', False), ('partner_id.coop_is_participant', '=', True),
        ('partner_id.is_company', '=', False), ('partner_id.name', 'not in', TEST_NAMES)])
    if len(users) < 20:
        return 0
    showcase = env['res.users'].sudo().search([('login', '=', login)], limit=1)
    students = users.mapped('partner_id')
    rnd = random.Random('courses-20260926')
    now = datetime.now().replace(microsecond=0)
    made = 0
    my_courses = 0
    for topic, courses in COURSES.items():
        for index, (title, word, level, summary) in enumerate(courses):
            author = rnd.choice(users)
            published = rnd.random() > 0.07
            created = now - timedelta(days=rnd.randint(5, 330))
            channel = Channel.create({
                'name': title,
                'description_short': '<p>%s</p>' % summary,
                'description': '<p>%s</p><p>Курс ведёт %s. Уровень — %s.</p>' % (
                    summary, author.partner_id.name,
                    {'basic': 'начальный', 'middle': 'средний', 'advanced': 'продвинутый'}[level]),
                'coop_topic': topic, 'coop_level': level,
                'user_id': author.id,
                'channel_type': 'training',
                'enroll': 'public',
                'visibility': 'public',
                'is_published': published,
                'sequence': index + 1,
                'image_1920': _cover(env, word, rnd, topic),
                'completed_template_id': False,
                'publish_template_id': False,
            })
            env.cr.execute('UPDATE slide_channel SET create_date = %s WHERE id = %s',
                           [created, channel.id])
            pool = LESSONS[topic]
            count = rnd.randint(4, min(9, len(pool)))
            picked = pool[:2] + sorted(rnd.sample(pool[2:], count - 2), key=pool.index)
            slides = Slide.browse()
            for seq, lesson in enumerate(picked):
                slides |= Slide.create({
                    'name': lesson, 'channel_id': channel.id, 'sequence': seq + 1,
                    'slide_category': 'article', 'is_published': True,
                    'completion_time': round(rnd.choice([0.15, 0.25, 0.33, 0.5, 0.75, 1.0]), 2),
                    'html_content': _lesson_html(title, lesson, word, rnd),
                })
            made += 1 + len(slides)
            if not published:
                continue
            # Ученики: у свежих и продвинутых курсов меньше, разброс по прогрессу.
            size = rnd.choice([0, 3, 6, 9, 14, 22, 35, 48]) if level != 'advanced' \
                else rnd.choice([0, 2, 4, 7, 12])
            members = rnd.sample(list(students), min(size, len(students)))
            if showcase and my_courses < 7 and rnd.random() < 0.12 \
                    and showcase.partner_id not in members:
                members.append(showcase.partner_id)
                my_courses += 1
            if members:
                channel._action_add_members(env['res.partner'].browse([p.id for p in members]))
            SlidePartner = env['slide.slide.partner'].sudo()
            for partner in members:
                done = rnd.choice([0, 0, 1, 2, len(slides) // 2, len(slides) - 1, len(slides),
                                   len(slides)])
                if done > 0:
                    SlidePartner.create([{
                        'slide_id': slide.id, 'channel_id': channel.id, 'partner_id': partner.id,
                        'completed': True,
                    } for slide in slides[:done]])
                    made += done
            if members:
                env['slide.channel.partner'].sudo().search(
                    [('channel_id', '=', channel.id)])._recompute_completion()
            # Отзывы — от части учеников, оценки неровные.
            reviewers = [p for p in members if rnd.random() < 0.3][:12]
            for partner in reviewers:
                env['rating.rating'].sudo().create({
                    'res_model_id': env['ir.model']._get_id('slide.channel'),
                    'res_id': channel.id, 'partner_id': partner.id,
                    'rated_partner_id': author.partner_id.id,
                    'rating': rnd.choices([5, 4, 3, 2], weights=[55, 30, 10, 5])[0],
                    'feedback': rnd.choice(REVIEWS), 'consumed': True,
                })
                made += 1
    Channel.search([('coop_topic', '!=', False)]).write({
        'completed_template_id': completed_template.id if completed_template else False,
        'publish_template_id': publish_template.id if publish_template else False,
    })
    Param.set_param(PARAM, VERSION)
    _logger.info('Образование: курсы, уроки, ученики и отзывы — %s записей', made)
    return made
