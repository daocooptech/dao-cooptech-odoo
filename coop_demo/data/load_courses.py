def _cover(env, word, rnd, topic=None):
    """Фотография с платформы по смыслу: ресурс, вакансия, проект,
    предложение навыка — со словом курса в названии и с картинкой; если
    такой нет — со словом темы."""
    for candidate in [word] + rnd.sample(TOPIC_WORDS.get(topic, []), len(TOPIC_WORDS.get(topic, []))):
        image = _cover_by(env, candidate, rnd)
        if image:
            return image
    return False


def _cover_by(env, word, rnd):
    for model in ('coop.resource', 'coop.skill.offer', 'coop.vacancy', 'coop.project',
                  'coop.event', 'coop.intangible'):
        if model not in env:
            continue
        Model = env[model].sudo()
        if 'image_1920' not in Model._fields:
            continue
        found = Model.search([('name', 'ilike', word), ('image_1920', '!=', False)], limit=12)
        if found:
            return rnd.choice(found).image_1920
    return False


