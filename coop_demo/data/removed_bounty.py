def purge_platform_tasks(env):
    Task = env['coop.bounty.task'].sudo()
    tasks = Task.search([('name', 'in', list(REMOVED)), ('payer_kind', '=', 'platform'),
                         ('coop_source_ref', '=', False)])
    count = len(tasks)
    tasks.unlink()
    return count
