def _fill(env, category):
    Resource = env['coop.resource'].sudo().with_context(tracking_disable=True)
    Attribute = env['coop.attribute'].sudo()
    options = {a.code: {o.name: o.code for o in a.option_ids}
               for a in Attribute.search([('value_type', 'in',
                                           ('selection', 'tags'))])}
    options['__tags__'] = set(Attribute.search(
        [('value_type', '=', 'tags')]).mapped('code'))
    filled = 0
    roots = [c.id for c in (category(n) for n in ASSIGN) if c]
    leaf_ids = env['coop.resource.category'].sudo().search(
        [('id', 'child_of', roots)]).ids
    for resource in Resource.search(DEMO + [('category_id', 'in', leaf_ids)]):
        # Ветка — собственная рубрика объявления: у листа свои списки.
        full_name = resource.category_id.complete_name
        definition = {d.get('name'): d for d in
                      (resource.category_id.attribute_definition or [])}
        current, repaired = _raw(env, resource, definition, options)
        rnd = random.Random(resource.id * 7919 + 483)
        new = dict.fromkeys(repaired)
        merged = dict(current)
        # Площадь, названная в заголовке, главнее придуманной.
        said = re.search(r'(\d+(?:[.,]\d+)?)\s*м²', _title(resource.name))
        if said and 'area_m2' in definition:
            area = float(said.group(1).replace(',', '.'))
            if merged.get('area_m2') != area:
                new['area_m2'] = merged['area_m2'] = area
        for code in definition:
            have = merged.get(code)
            if have is False and definition[code].get('type') == 'boolean':
                continue
            if have not in (None, False, '', []) and \
                    not _implausible(code, have, merged, options):
                continue
            value = _value(code, resource, full_name, rnd, options, merged)
            if value is not None:
                new[code] = value
                merged[code] = value
        for code, value in _agree(merged, resource, full_name, rnd,
                                  options).items():
            if code in definition and merged.get(code) != value:
                new[code] = merged[code] = value
        for code in [c for c in ('elevator_kind',) if merged.get(c) is None]:
            merged.pop(code, None)
        if new:
            with env.cr.savepoint():
                resource.attrs = {k: v for k, v in merged.items()
                                  if k in definition}
                filled += 1
    return filled


def _raw(env, resource, definition, options):
    """Значения как лежат в базе.

    Чтение поля через ORM отдаёт метки подписями («Во двор, На улицу»), и
    запись обратно кладёт в базу строку вместо списка ключей — движок
    такую метку не показывает. Так испортились «Окна», «Парковка», «Тип
    лифта» при повторных прогонах загрузчиков (замер 24.11). Читаем
    сырой JSON и чиним подписи в ключи.
    """
    env.cr.execute('SELECT attrs FROM coop_resource WHERE id = %s',
                   (resource.id,))
    row = env.cr.fetchone()
    value = (row and row[0]) or {}
    out, repaired = {}, []
    for code, item in value.items():
        kind = (definition.get(code) or {}).get('type')
        # «Нет» у флажка — тоже ответ: иначе жребий перекидывал его заново
        # в каждую выкатку.
        if item in (None, '', []) and item is not False or (
                item is False and kind != 'boolean'):
            continue
        if kind == 'tags' and isinstance(item, str):
            labels = [x.strip() for x in item.split(',')]
            known = set(options.get(code, {}).values())
            codes = [x if x in known else options.get(code, {}).get(x)
                     for x in labels]
            item = [c for c in codes if c]
            repaired.append(code)
            if not item:
                continue
        out[code] = item
    return out, repaired


REMOTE_KINDS = ('Обучение', 'IT и разработка', 'Тексты и переводы',
                'Консультирование', 'Бухгалтерия', 'Юридические', 'Дизайн',
                'Маркетинг')


def _agree(cur, resource, branch, rnd, options):
    """Согласовать поля между собой: то, что по отдельности правдоподобно,
    вместе бывает неправдой."""
    fix = {}
    low = _title(resource.name)
    opt = lambda code, label: options.get(code, {}).get(label)  # noqa: E731
    # Новостройка не бывает 1987 года.
    if cur.get('flat_market') == opt('flat_market', 'Новостройка') and \
            int(cur.get('build_year') or 0) < 2019:
        fix['build_year'] = rnd.randint(2019, 2026)
    # «Черновая отделка» и «Чистовая» вместе — неправда.
    rough = opt('renovation', 'Черновая отделка')
    if cur.get('renovation') == rough and cur.get('finishing') == \
            opt('finishing', 'Чистовая'):
        fix['finishing'] = opt('finishing', rnd.choice(['Без отделки',
                                                        'Предчистовая']))
    elif cur.get('renovation') in (opt('renovation', 'Косметический'),
                                   opt('renovation', 'Евроремонт'),
                                   opt('renovation', 'Дизайнерский')) and \
            cur.get('finishing') and \
            cur['finishing'] != opt('finishing', 'Чистовая'):
        fix['finishing'] = opt('finishing', 'Чистовая')
    # Лифта нет — нет и его типа; тип — списком вариантов, не строкой.
    if cur.get('elevator_count') == opt('elevator_count', 'Нет'):
        if cur.get('elevator_kind'):
            fix['elevator_kind'] = None
    elif isinstance(cur.get('elevator_kind'), str):
        fix['elevator_kind'] = [opt('elevator_kind', 'Пассажирский')]
    # Грузоподъёмность меньше разрешённой массы, у грузовика — до 25 т.
    if 'Грузовики' in branch and cur.get('capacity_ton'):
        cap = float(cur['capacity_ton'])
        if cap > 25:
            cap = round(rnd.uniform(1.5, 25), 1)
            fix['capacity_ton'] = cap
        if float(cur.get('gvw_t') or 0) <= cap:
            fix['gvw_t'] = round(cap * rnd.uniform(1.6, 2.0), 1)
    # «Отдам старое», «б/у» — не новое.
    if cur.get('condition') == opt('condition', 'Новое') and any(
            w in low for w in ('отдам', 'стар', 'б/у', 'после ремонта',
                               'после сезона', 'бывш')):
        fix['condition'] = opt('condition', 'Рабочее')
    # «Вид» — по названию, если оно его называет (правила уточняются).
    label = _kind_hint(resource.name, KINDS.get(branch) or [])
    if label and cur.get('item_kind') and \
            cur['item_kind'] != opt('item_kind', label):
        fix['item_kind'] = cur['item_kind'] = opt('item_kind', label)
    # Ремонт мотоблока удалённо не делают.
    kinds = {v: k for k, v in options.get('item_kind', {}).items()}
    if cur.get('work_place') == opt('work_place', 'Удалённо') and \
            kinds.get(cur.get('item_kind')) not in REMOTE_KINDS:
        fix['work_place'] = opt('work_place', rnd.choice(
            ['У заказчика', 'У исполнителя']))
    return {k: v for k, v in fix.items() if v is not None or k == 'elevator_kind'}


def _implausible(code, value, cur, options):
    try:
        number = float(value)
    except (TypeError, ValueError):
        return False
    if code == 'area_m2' and cur.get('flat_rooms') in FLAT_AREA:
        low, high = FLAT_AREA[cur['flat_rooms']]
        return not (low <= number <= high)
    if code == 'ceiling_height_m' and cur.get('flat_rooms'):
        return not (2.4 <= number <= 3.6)       # жилой дом, не склад
    if code == 'floor' and cur.get('floors_total'):
        return number > float(cur['floors_total'])
    if code == 'kitchen_m2' and cur.get('area_m2'):
        return number > float(cur['area_m2']) * 0.35
    return False


def _pick(options, code, labels, rnd):
    pool = [options[code][x] for x in labels if x in options.get(code, {})]
    return rnd.choice(pool) if pool else None


def _value(code, resource, branch, rnd, options, cur):
    name = resource.name or ''
    low = _title(name)
    opts = options.get(code, {})
    if code == 'item_kind':
        pool = KINDS.get(branch) or []
        label = _kind_hint(name, pool)
        return opts.get(label) if label else None
    if code == 'area_m2':
        m = re.search(r'(\d+(?:[.,]\d+)?)\s*м²', low)
        if m:
            return float(m.group(1).replace(',', '.'))
    if code == 'ceiling_height_m' and 'Жилая' in branch:
        return rnd.choice([2.5, 2.6, 2.7, 2.7, 2.8, 3.0, 3.2])
    if code == 'area_m2' and cur.get('flat_rooms') in FLAT_AREA:
        low_a, high_a = FLAT_AREA[cur['flat_rooms']]
        return round(rnd.uniform(low_a, high_a), 1)
    if code == 'kitchen_m2':
        area = float(cur.get('area_m2') or 45)
        return round(max(5.0, min(area * rnd.uniform(0.14, 0.25), 25)), 1)
    if code == 'floors_total':
        return rnd.choice([1, 2, 2, 3]) if 'Дома' in branch else rnd.randint(5, 25)
    if code == 'floor':
        return rnd.randint(1, int(cur.get('floors_total') or 9))
    if code == 'brand':
        return None      # марку берём только из названия (load_branch_attributes)
    if code in ('maker', 'perf', 'chassis', 'gost'):
        return None      # текст — только со слов автора объявления
    hint = _hint(code, low, opts)
    if hint is not None:
        return hint
    if code == 'thickness_mm':
        m = re.search(r'толщин\w*\s*(\d+)', low)
        if m:
            return float(m.group(1))
        return float(rnd.choice([50, 100, 150])) if 'Изоляция' in branch \
            else float(rnd.choice([10, 20, 30, 40]))
    if code in ('width_cm', 'height_cm') and 'Ворота' in branch:
        m = re.search(r'(\d+(?:[.,]\d+)?)\s*[×x]\s*(\d+(?:[.,]\d+)?)', low)
        if m:
            w, h = (float(x.replace(',', '.')) for x in m.groups())
            return int((w if code == 'width_cm' else h) * 100)
        return rnd.choice([250, 300, 400, 500]) if code == 'width_cm' else \
            rnd.choice([200, 250, 300, 400])
    if code == 'area_m2' and 'срубы' in branch:
        m = re.search(r'(\d+)\s*[×x]\s*(\d+)', low)
        if m:
            return float(int(m.group(1)) * int(m.group(2)))
    if code == 'wall_material' and 'срубы' in branch:
        return opts.get('Брус') if 'брус' in low else opts.get('Бревно')
    if code == 'area_m2' and branch.startswith(SB):
        return float(rnd.choice([10, 20, 30, 50, 80, 120]))
    if opts:
        value_type = 'tags' if code in options.get('__tags__', ())             else 'selection'
        labels = list(opts)
        if value_type == 'tags':
            return [opts[x] for x in rnd.sample(labels, rnd.randint(1, min(2, len(labels))))]
        return rnd.choice(list(opts.values()))
    ranges = {
        'metro_walk_min': (3, 25), 'rooms_in_flat': (2, 5), 'city_km': (5, 90),
        'seats': (2, 7), 'gvw_t': (3.5, 40.0), 'op_mass_t': (1.5, 45.0),
        'bucket_m3': (0.1, 2.5), 'dig_depth_m': (2.0, 7.5), 'boom_m': (14.0, 60.0),
        'axles': (1, 3), 'passengers': (1, 8), 'width_m': (1.2, 3.2),
        'draft_m': (0.3, 1.2), 'max_motor_hp': (5, 150), 'tire_width': (175, 285),
        'tire_profile': (45, 75), 'tread_mm': (3.0, 8.5), 'wheel_inch': (16, 29),
        'width_cm': (40, 220), 'height_cm': (40, 220), 'depth_cm': (30, 90),
        'shelf_load_kg': (40, 300), 'movers': (0, 3), 'term_months': (3, 60),
        'rate_pct': (4.0, 24.0), 'fuel_100': (5.5, 13.0),
        'ceiling_height_m': (2.5, 3.3), 'land_sotka': (4.0, 25.0),
        'engine_power_hp': (40, 320), 'engine_hours': (300, 9000),
        'capacity_ton': (5.0, 60.0), 'length_m': (2.5, 13.6),
        'mileage_km': (20_000, 420_000),
    }
    if code in ranges:
        a, b = ranges[code]
        return round(rnd.uniform(a, b), 1) if isinstance(a, float) else \
            rnd.randint(a, b)
    booleans = ('damaged', 'guarded', 'with_tenant', 'trailer_incl', 'motor_incl',
                'runflat', 'urgent_fee', 'with_vat', 'with_materials', 'regular',
                'collateral')
    if code in booleans:
        return rnd.random() < (0.15 if code in ('damaged', 'runflat', 'regular')
                               else 0.45)
    return None


