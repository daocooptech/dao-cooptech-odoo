def names(base):
    """Все названия темы: заголовок × уточнения, заголовки вперемешку."""
    heads, specs = REAL_OFFERS[base]
    out = []
    for combo in itertools.product(*specs):
        for head in heads:
            out.append('%s %s%s' % (head, combo[0], ''.join(', ' + x for x in combo[1:])))
    return out


def heads(base):
    return REAL_OFFERS.get(base, ((), ()))[0]
