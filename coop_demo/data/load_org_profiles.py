"""Заполненные карточки организаций — по несколько на каждую правовую форму.

Каталог из макета даёт название, город и специализацию, но профиль
организации при этом остаётся пустым: ни реквизитов, ни адреса, ни связи.
На пустом профиле не видно ни самого экрана, ни того, чем ООО отличается
от потребительского кооператива, — а именно это в разделе и показывают.

Поэтому по каждой форме справочника заводится несколько организаций с
полностью заполненной карточкой, а недостающие создаются.

Про ИНН, КПП и ОГРН. Номера здесь синтетические и построены так, чтобы их
нельзя было спутать с настоящими: код региона «00» в ИНН и в ОГРН не
существует, такого субъекта в стране нет. Контрольные разряды при этом
считаются по действующим правилам, поэтому поля выглядят и ведут себя как
настоящие — но ни один из этих номеров никогда не совпадёт с номером
реальной организации. Это важнее, чем кажется: логотипы в каталоге взяты у
настоящих компаний, и номер с настоящим кодом региона рядом с их знаком
превратил бы демонстрационную запись в подобие выписки из реестра.
"""
