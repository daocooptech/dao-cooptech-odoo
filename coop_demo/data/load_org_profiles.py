# Коэффициенты контрольных разрядов ИНН — из приказа ФНС о порядке
# формирования идентификационного номера налогоплательщика.
INN_WEIGHTS_10 = [2, 4, 10, 3, 5, 9, 4, 6, 8]
INN_WEIGHTS_11 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
INN_WEIGHTS_12 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]


def _inn_checksum(digits, weights):
    return sum(int(d) * w for d, w in zip(digits, weights)) % 11 % 10


def _inn(seed, individual=False):
    """ИНН с верной контрольной суммой и несуществующим кодом региона.

    Первые две цифры — код субъекта федерации; «00» не выдаётся никогда,
    поэтому такой номер заведомо не принадлежит никакой организации.
    """
    if individual:
        body = '00' + '%08d' % (seed * 7919 % 10 ** 8)
        first = _inn_checksum(body, INN_WEIGHTS_11)
        second = _inn_checksum(body + str(first), INN_WEIGHTS_12)
        return body + str(first) + str(second)
    body = '00' + '%07d' % (seed * 7919 % 10 ** 7)
    return body + str(_inn_checksum(body, INN_WEIGHTS_10))


def _ogrn(seed, individual=False):
    """ОГРН или ОГРНИП с верным контрольным разрядом.

    Разрядность разная: 13 знаков у организации, 15 у предпринимателя.
    Контрольный разряд — остаток от деления числа без него на 11 (на 13
    для ОГРНИП), взятый по последней цифре.
    """
    if individual:
        body = '3' + '%02d' % (seed % 100) + '00' + '%09d' % (seed * 6841 % 10 ** 9)
        return body + str(int(body) % 13 % 10)
    body = '1' + '%02d' % (seed % 100) + '00' + '%07d' % (seed * 6841 % 10 ** 7)
    return body + str(int(body) % 11 % 10)


def _kpp(seed):
    return '00' + '%02d' % (seed % 100) + '01001'


