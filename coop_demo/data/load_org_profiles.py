STREETS = ['ул. Кооперативная', 'ул. Артельная', 'пр-т Мира', 'ул. Заводская',
           'ул. Садовая', 'наб. Речная', 'ул. Промысловая', 'ул. Луговая']


def _domain(name, seed):
    """Домен из порядкового номера, а не из названия.

    Транслитерировать русское название в домен — значит получить адреса
    вроде «potrebitelskoe-obschestvo-hlebnyy-ryad.ru», которых не бывает.
    Короткий номерной домен честнее: видно, что адрес демонстрационный.
    """
    return 'https://coop-%03d.example' % seed


def load_org_profiles(env, specializations, marks):
    forms = {form.code: form for form in env['coop.legal.form'].search([])}
    country_ru = env['res.country'].search([('code', '=', 'RU')], limit=1)
    Partner = env['res.partner']

    created = filled = 0
    seed = 0
    for code, samples in SAMPLES.items():
        form = forms.get(code)
        if not form:
            _logger.warning('Правовой формы «%s» нет в справочнике', code)
            continue

        for name, city, specialization_name in samples:
            seed += 1
            individual = code == 'ip'
            values = {
                'is_company': True,
                'city': city,
                'country_id': country_ru.id if country_ru else False,
                'coop_is_participant': True,
                'coop_legal_form_id': form.id,
                'coop_inn': _inn(seed, individual),
                'coop_ogrn': _ogrn(seed, individual),
                # У предпринимателя КПП не бывает: он не состоит на учёте
                # по месту нахождения обособленных подразделений.
                'coop_kpp': False if individual else _kpp(seed),
                'coop_registered_on': '%04d-%02d-%02d' % (
                    2000 + seed % 24, (seed % 12) + 1, (seed * 3 % 27) + 1),
                'coop_charter_url': '%s/charter.pdf' % _domain(name, seed),
                'street': '%s, %d' % (STREETS[seed % len(STREETS)], (seed * 7) % 90 + 1),
                'zip': '%06d' % (100000 + seed * 137 % 500000),
                'phone': '+7 (%03d) %03d-%02d-%02d' % (
                    300 + seed % 600, seed * 13 % 1000, seed % 100, (seed * 7) % 100),
                'email': 'info@coop-%03d.example' % seed,
                'website': _domain(name, seed),
                'coop_trust': 55 + (seed * 13) % 45,
                'coop_symbol_mark': True,
            }
            specialization = specializations.get(specialization_name)
            if specialization:
                values['coop_specialization_id'] = specialization.id
            else:
                _logger.warning('Специализации «%s» нет в справочнике',
                                specialization_name)

            existing = Partner.search([
                ('name', '=', name), ('is_company', '=', True)], limit=1)
            if existing:
                existing.write(values)
                filled += 1
            else:
                mark = marks.next()
                if mark:
                    with open(mark, 'rb') as fh:
                        values['image_1920'] = base64.b64encode(fh.read())
                else:
                    values['image_1920'] = emblems.emblem(name, specialization_name)
                Partner.create(dict(values, name=name))
                created += 1

    _logger.info('Заполненные карточки организаций: создано %s, дополнено %s, '
                 'форм охвачено %s', created, filled, len(SAMPLES))
