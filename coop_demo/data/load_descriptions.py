def _match(text):
    """Вид по самому раннему слову: в названии главное слово стоит
    первым — «Стеллажи для рассады» это стеллажи, а не рассада. При
    равном месте побеждает более длинное слово: «зернодробилка» —
    оборудование, а не зерно."""
    best = None
    for kind, words in KINDS:
        for word in words:
            pos = text.find(word)
            if pos >= 0 and (best is None or (pos, -len(word)) < best[0]):
                best = ((pos, -len(word)), kind)
    return best and best[1]


def _kind(record):
    """Вид вещи: по названию, иначе по типу ресурса, иначе по рубрике.

    Рубрика — последней: у потребностей проектов она проставлена по
    проекту, а не по вещи, и «Инженер-технолог» с рубрикой «Склады»
    читался как помещение."""
    # Только первая часть названия: хвост «— Кооперативный склад —
    # Вологда» — это проект и город, а не сама вещь.
    kind = _match((record.name or '').split(' — ')[0].lower() + ' ')
    if kind:
        return kind
    if record.resource_type == 'financial':
        return 'finance'
    if record.resource_type == 'labour':
        return 'labour'
    if record.category_id:
        kind = _match((record.category_id.name or '').lower() + ' ')
        if kind:
            return kind
    return 'generic'


def _plain(html):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', html or '')).strip()


def _esc(text):
    return (text or '').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def _facts(record, rng, request):
    """Строки списка «Что важно знать» — только из того, что есть в записи."""
    facts = []
    qty = record.quantity_display
    # «1» без единицы ничего не говорит читающему — не пишем.
    if qty and (record.uom_label or (record.quantity or 0) != 1):
        facts.append(('Нужно' if request else 'В наличии') + ': ' + qty)
    if not request and record.condition == 'new':
        facts.append(rng.choice(['Состояние: новое, не использовалось',
                                 'Состояние: новое']))
    elif not request and record.condition == 'used':
        facts.append(rng.choice(['Состояние: б/у, в рабочем виде',
                                 'Б/у, без серьёзных следов износа',
                                 'Состояние: б/у, всё исправно']))
    if record.city:
        facts.append(('Где: ' if request else 'Забирать: ') + record.city
                     + (', ' + record.pickup_point if record.pickup_point else ''))
    codes = [code for code in record.method_ids.mapped('code') if code in METHODS]
    if codes:
        if request:
            facts.append('Готовы: ' + ', '.join(REQUEST_METHODS[code] for code in codes))
        else:
            facts.append('Способы: ' + ', '.join(METHODS[code] for code in codes))
    if request:
        facts.append('Срок: ' + rng.choice(DEADLINES))
    if record.bargain:
        facts.append(rng.choice(['Торг уместен', 'Торг при осмотре',
                                 'Цену обсудим']))
    elif not request and codes and 'free' not in codes:
        facts.append(rng.choice(['Без торга — цена честная',
                                 'Цена окончательная']))
    return facts


def _compose(record):
    rng = random.Random(record.id * 7919 + 17)
    request = record.listing_type == 'request'
    kind = _kind(record)
    hooks = (REQUEST_HOOK if request else OFFER_HOOK)[kind]
    details = list((REQUEST_DETAILS if request else OFFER_DETAILS)[kind])
    generic = list((REQUEST_DETAILS if request else OFFER_DETAILS)['generic'])
    rng.shuffle(details)
    rng.shuffle(generic)
    parts = ['<p>%s</p>' % _esc(rng.choice(hooks))]

    project = record.project_id if 'project_id' in record._fields else False
    if project:
        parts.append('<p>%s</p>' % _esc(rng.choice([
            'Нужно для проекта «%s». Проект кооперативный, всё прозрачно: '
            'смета и ход работ открыты участникам.',
            'Это потребность проекта «%s» — без неё следующий этап не '
            'начнётся. Участие засчитаем в проекте.',
            'Собираем ресурсы для проекта «%s». Откликнувшимся покажем план '
            'и расскажем, на каком мы этапе.',
        ]) % project.name))

    body = details[:rng.randint(4, 5)] + ([] if request else generic[:1])
    parts.append('<p>%s</p>' % _esc(' '.join(body)))

    facts = _facts(record, rng, request)
    if facts:
        # Списком в строках абзаца, а не `ul`: поле описания на витрине
        # (`coop_block`) держит только абзацы и переносы — с другими
        # тегами оно прячет карандаш правки.
        parts.append('<p>%s<br>%s</p>' % (
            rng.choice(['Что важно знать:', 'Коротко:', 'Подробности:']),
            '<br>'.join('— ' + _esc(fact) for fact in facts)))

    codes = [code for code in record.method_ids.mapped('code') if code in TERMS]
    if codes and not request:
        terms = [rng.choice(TERMS[code]) for code in codes[:3]]
        parts.append('<p>%s</p>' % _esc(' '.join(terms)))

    is_org = bool(record.owner_id and record.owner_id.is_company)
    about = list(ABOUT_ORG if is_org else ABOUT_PERSON)
    rng.shuffle(about)
    parts.append('<p>%s</p>' % _esc(' '.join(about[:2])))
    if request:
        closing = list(CLOSING_REQUEST)
    else:
        closing = list(CLOSING_ORG if is_org else CLOSING_PERSON)
    rng.shuffle(closing)
    parts.append('<p>%s</p>' % _esc(' '.join(closing[:2])))
    return '<div class="%s">%s</div>' % (MARK, ''.join(parts))


def fill_resource_descriptions(env):
    """Дописать описания ресурсам, у которых их нет или они в строку."""
    Resource = env['coop.resource'].sudo().with_context(
        active_test=False, tracking_disable=True, mail_notrack=True)
    filled = 0
    for record in Resource.search([]):
        current = record.description or ''
        if MARK not in current and len(_plain(current)) >= MIN_LENGTH:
            continue
        text = _compose(record)
        if text != current:
            record.description = text
            filled += 1
    _logger.info('Описания ресурсов: дописано %s', filled)
    return filled
