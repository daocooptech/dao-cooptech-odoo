# -*- coding: utf-8 -*-
"""Снимки каталогам — одним проходом и с переклейкой неверных.

Зачем понадобилось. Каждый загрузчик ставил снимок сам и только там, где
поле пусто. Пока правила не менялись, это работало; стоило правилу
появиться или исправиться — старые записи оставались с тем, что им
досталось при первом прогоне. Пересчёт боевой базы 20 сентября 2026
показал, сколько от этого накопилось:

* 2102 записи без снимка вовсе — из них 1375 под названиями, к которым
  правила не было (крепёж, кабель, топливо, страхование, собрания);
* десяток записей с чужим снимком из самой первой закачки — у
  «Бетономешалки на 180 л» стояла морковь, у «Лесов строительных» —
  осенний лес. Именно это владелец и увидел: «в потребностях у
  бетономешалки картинка моркови»;
* вакансии и предложения навыка со снимком из макета, где он проставлен
  наугад: у «Швеи» сварка, у «Повара» столярный цех.

Что делает. Идёт по каталогам и для каждой записи считает, какой снимок
ей полагается: у вакансии и навыка — по роду занятий, у остального — по
названию. Дальше три случая:

* поле пусто — ставит;
* стоит снимок из наших наборов, но не тот, что полагается, — меняет;
* стоит снимок не из наборов — меняет: в наполнении своих снимков ни у
  кого нет, а этот пришёл из первой закачки и не совпадает с названием.

Лица участников этим проходом не трогаются: там своё правило и свой
разбор — `load_faces`.
"""
import base64
import hashlib
import logging
import os

from . import emblems, load_resources, photos, professions

_logger = logging.getLogger(__name__)

HERE = os.path.dirname(os.path.abspath(__file__))
IMG_DIR = os.path.join(os.path.dirname(HERE), 'static', 'img')

# Каталоги, которым снимок положен: модель, поле снимка, поле
# специализации (если у записи есть род занятий).
КАТАЛОГИ = (
    ('coop.vacancy', 'image_1920', 'coop_specialization_id'),
    ('coop.skill.offer', 'image_1920', 'coop_specialization_id'),
    ('coop.resource', 'image_1920', None),
    ('coop.intangible', 'image_1920', None),
    ('coop.event', 'image_1920', None),
    ('coop.program', 'image_1920', None),
    ('coop.groupbuy', 'image_1920', None),
    ('coop.deal', 'image_512', None),
    ('coop.auction', 'image_512', None),
    ('coop.warehouse.offer', 'image_1920', None),
)


def _отпечатки():
    """Отпечаток файла → путь, по всем нашим наборам снимков.

    Нужен, чтобы отличить наш снимок от чужого: чужой в наборе не
    числится, и по одному этому признаку видно, что запись досталась
    из старой закачки.
    """
    таблица = {}
    for dirpath, _dirs, names in os.walk(IMG_DIR):
        for имя in names:
            if not имя.lower().endswith(('.jpg', '.jpeg', '.png')):
                continue
            путь = os.path.join(dirpath, имя)
            with open(путь, 'rb') as fh:
                таблица[hashlib.sha256(fh.read()).hexdigest()] = путь
    return таблица


def _годные_для(имя, специализация):
    """Снимки, которые записи подходят: путь на диске → отпечаток.

    Не один снимок, а все допустимые: у предмета есть варианты
    (`cement-bag.jpg`, `cement-bag-2.jpg`), у занятия — несколько
    снимков. Пока стоит любой из них, менять нечего: иначе каждый прогон
    переставлял бы карточки с места на место.
    """
    пути = []
    if специализация:
        пути = [os.path.join(IMG_DIR, п) for п in professions.файлы(специализация)]
    if not пути:
        правило = load_resources._photo_by_name(имя or '')
        if правило:
            пути = [os.path.join(photos.PHOTO_DIR, в)
                    for в in photos._variants(правило)]
    return [п for п in пути if os.path.exists(п)]


def _подобрать(имя, специализация):
    """Снимок записи: сначала род занятий, потом название."""
    if специализация:
        снимок = professions.photo_for(имя, специализация)
        if снимок:
            return снимок
    return photos.photo_for(имя)


def ensure_photos(env):
    """Проставить и переклеить снимки во всех каталогах."""
    наши = _отпечатки()
    итог = {'поставлено': 0, 'переклеено': 0, 'знаком': 0}

    for модель, поле, поле_спец in КАТАЛОГИ:
        if модель not in env:
            continue
        Модель = env[модель].sudo()
        if поле not in Модель._fields:
            continue
        поставлено = переклеено = знаком = 0
        for счёт, запись in enumerate(Модель.search([])):
            # Кэш ORM держит каждый прочитанный снимок целиком, а их тут
            # тысячи по сотне килобайт. На боевой при гигабайте памяти
            # проход без сброса кэша съедает её весь и падает по OOM,
            # унося с собой всё обновление модуля.
            if счёт and not счёт % 200:
                env.invalidate_all()
            # Savepoint на запись: PostgreSQL обрывает транзакцию на
            # первой ошибке, и одна негодная запись тихо отменила бы все
            # снимки этого прогона.
            with env.cr.savepoint():
                специализация = ''
                if поле_спец and поле_спец in запись._fields:
                    значение = запись[поле_спец]
                    специализация = значение.display_name if значение else ''
                годные = _годные_для(запись.name, специализация)
                текущий = запись[поле]

                if текущий and годные:
                    отпечаток = hashlib.sha256(
                        base64.b64decode(текущий)).hexdigest()
                    если_наш = наши.get(отпечаток)
                    if если_наш and если_наш in годные:
                        continue

                снимок = _подобрать(запись.name, специализация)
                if снимок:
                    запись.write({поле: снимок})
                    if текущий:
                        переклеено += 1
                    else:
                        поставлено += 1
                    continue

                if not текущий:
                    # Предмет не опознан — знак организации честнее
                    # чужой фотографии.
                    род = специализация or запись.name
                    запись.write({поле: emblems.emblem(запись.name, род)})
                    знаком += 1

        _logger.info('Снимки %s: поставлено %s, переклеено %s, знаком %s',
                     модель, поставлено, переклеено, знаком)
        итог['поставлено'] += поставлено
        итог['переклеено'] += переклеено
        итог['знаком'] += знаком

    _logger.info('Снимки каталогов: поставлено %(поставлено)s, '
                 'переклеено %(переклеено)s, знаком %(знаком)s', итог)
    return итог['поставлено'] + итог['переклеено'] + итог['знаком']


def ensure_marks(env):
    """Знак каждой организации — из набора эмблем, и по одному разу.

    Знаки раздавались по порядку и только тем, у кого поле пусто. Пока
    набор не менялся, этого хватало; но часть файлов оказалась не
    знаками вовсе — спутниковый снимок, фотография здания, разворот
    удостоверения, — и, когда их убрали из набора, у организаций они
    остались: раздача до заполненного поля не доходит.

    Здесь наоборот: организация со знаком, которого в наборе больше нет,
    получает следующий свободный. Занятые считаются по самим карточкам,
    чтобы один знак не достался двоим.
    """
    файлы = [имя for имя in sorted(os.listdir(emblems.MARK_DIR))
             if имя.lower().endswith('.png')] if os.path.isdir(emblems.MARK_DIR) else []
    if not файлы:
        return 0
    отпечатки = {}
    for имя in файлы:
        путь = os.path.join(emblems.MARK_DIR, имя)
        with open(путь, 'rb') as fh:
            отпечатки[hashlib.sha256(fh.read()).hexdigest()] = имя

    Partner = env['res.partner'].sudo()
    организации = Partner.search([('is_company', '=', True)], order='id')

    занято = set()
    нужны = []
    for org in организации:
        снимок = org.image_1920
        имя = None
        if снимок:
            имя = отпечатки.get(hashlib.sha256(base64.b64decode(снимок)).hexdigest())
        if имя and имя not in занято:
            занято.add(имя)
        else:
            нужны.append(org)

    свободные = [имя for имя in файлы if имя not in занято]
    выдано = 0
    for org, имя in zip(нужны, свободные):
        with open(os.path.join(emblems.MARK_DIR, имя), 'rb') as fh:
            org.image_1920 = base64.b64encode(fh.read())
        выдано += 1

    _logger.info('Знаки организаций: выдано %s, без знака осталось %s',
                 выдано, max(0, len(нужны) - len(свободные)))
    return выдано
