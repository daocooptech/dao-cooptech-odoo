def move_misplaced(env):
    Category = env['coop.resource.category'].sudo()
    Resource = env['coop.resource'].sudo().with_context(
        active_test=False, tracking_disable=True, mail_notrack=True)
    records = Resource.search(DEMO + [('category_id', '!=', False)])
    moved = 0
    for words, full in MISPLACED:
        category = Category.search([('complete_name', '=', full)], limit=1)
        if not category:
            continue
        # Не `ilike`: база с локалью C регистр кириллицы не сводит.
        wrong = records.filtered(
            lambda r: r.category_id != category and r.write_uid.id <= 2
            and (r.name or '').lower().startswith(words))
        if wrong:
            # Набор у рубрики свой: значения прежней («тепловое» у печника)
            # снимаются, новые ставит `fill_bare`.
            wrong.write({'category_id': category.id})
            env.flush_all()
            env.cr.execute('UPDATE coop_resource SET attrs = NULL WHERE id IN %s',
                           (tuple(wrong.ids),))
            env.invalidate_all()
        moved += len(wrong)
    _logger.info('Каталоги: в свою рубрику перенесено %s', moved)
    return moved


