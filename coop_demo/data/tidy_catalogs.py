def _bounds(name, unit, rent):
    low = (name or '').lower()
    table = [(a, b, c, None) for a, b, c in
             (MONTH_RENT if unit in MONTHS else RENT if unit in DAYS else [])] if rent else SALE
    for rule, lo, hi, per in table:
        if not re.match(rule, low):
            continue
        if per:
            m = re.search(r'(\d+)\s*' + per, low)
            if not m:
                return None
            # «2 стола», «100 л в неделю» — цена за всё количество.
            lo, hi = lo * int(m.group(1)), hi * int(m.group(1))
        if rule == 'цемент' and unit == 'тонна':
            lo, hi = 8500, 11000
        return lo, hi
    return None


def _nice(value):
    step = 10 if value < 1000 else 100 if value < 20000 else 1000 if value < 300000 else 5000
    return float(round(value / step) * step) if value >= 20 else round(value, 1)


def _fit(price, lo, hi, rate, seed):
    """Новая цена в валюте записи или None, если стоящая правдоподобна."""
    if lo * 0.7 <= price * rate <= hi * 1.4:
        return None
    rnd = random.Random('price483:%s' % seed)
    value = rnd.uniform(lo, hi)
    return _nice(value / rate)


def fix_prices(env):
    Resource = env['coop.resource'].sudo().with_context(
        active_test=False, tracking_disable=True, mail_notrack=True,
        coop_no_price_sync=True)
    fixed = 0
    for resource in Resource.search(DEMO + [('listing_type', '=', 'offer')]):
        if resource.write_uid.id > 2:
            continue
        rate = RATE.get(resource.currency_id.name)
        if not rate:
            continue
        changed = False
        for term in resource.term_ids.filtered(
                lambda t: t.price and t.code in ('sale', 'rent', 'installment', 'leasing')):
            bounds = _bounds(resource.name, term.price_unit_label, term.code == 'rent')
            price = bounds and _fit(term.price, *bounds, rate,
                                    '%s:%s' % (resource.id, 'rent' if term.code == 'rent' else 'sale'))
            if price and price != term.price:
                term.write({'price': price})
                changed = True
        priced = resource.term_ids.filtered(
            lambda t: t.code != 'free' and t.price).sorted('sequence')[:1]
        sale = priced and priced.code == 'sale' and _bounds(resource.name, priced.price_unit_label, False)
        if sale and resource.price and _fit(resource.price, *sale, rate, resource.id):
            changed = True
        if priced and changed:
            # Рассрочка и продажа — от одной цены; карточка — от первого способа.
            if priced.price_kind != 'none' and resource.price != priced.price:
                resource.price = priced.price
            # «28 000 ₽/сутки» у цены продажи: единица — того же способа.
            if priced.code == 'sale' and resource.price_unit_label in DAYS + MONTHS:
                resource.price_unit_label = priced.price_unit_label or False
        elif not priced and resource.price:
            place = PLACE.match((resource.name or '').lower())
            if place:
                area = int(place.group(2))
                price = _fit(resource.price, 250 * area, 520 * area, rate, resource.id)
                if price and price != resource.price:
                    resource.price = price
                    changed = True
                if resource.price_unit_label != 'мес':
                    resource.price_unit_label = 'мес'
                    changed = True
            else:
                unit = resource.price_unit_label
                bounds = _bounds(resource.name, unit, unit in DAYS + MONTHS)
                price = bounds and _fit(resource.price, *bounds, rate, resource.id)
                if price and price != resource.price:
                    resource.price = price
                    changed = True
        fixed += changed
    # «Кредитная линия — до 2 ₽»: в исходнике было «2 млн».
    for start, price in (('Инвестиции в кооперативный склад', 5000000),
                         ('Кредитная линия для малого бизнеса', 2000000),
                         ('Сдам дачу на лето', 45000)):
        for resource in Resource.search(DEMO + [('name', '=like', start + '%'), ('price', '>', 0),
                                         ('price', '<', 1000), ('listing_type', '=', 'offer')]):
            if resource.write_uid.id > 2:
                continue
            resource.term_ids.filtered(lambda t: 0 < t.price < 1000).write({'price': price})
            resource.price = price
            fixed += 1
    _logger.info('Каталоги: цена поправлена у %s объявлений', fixed)
    return fixed


