def fix_services(env):
    Offer = env['coop.skill.offer'].sudo().with_context(
        active_test=False, tracking_disable=True, mail_notrack=True)
    ours = {t[0] for titles in TITLES.values() for t in titles}
    fixed = 0
    for spec, titles in TITLES.items():
        offers = Offer.search([
            ('coop_specialization_id.name', '=', spec), ('partner_id.is_company', '=', True),
            ('import_key', '!=', False)], order='id').filtered(
            lambda o: not o.import_key.startswith('service483#') and o.write_uid.id <= 2)
        taken = set(offers.mapped('name')) & ours
        free = [t for t in titles if t[0] not in taken]
        for offer in offers:
            if offer.name in ours or not free:
                continue
            name, rate, period, text = free.pop(0)
            offer.write({
                'name': name, 'rate': rate, 'rate_period': period,
                'rate_kind': 'from' if rate >= 10000 else 'exact',
                'employment': 'part' if period == 'month' else 'once',
                'description': '<p>%s</p>' % text})
            fixed += 1
    _logger.info('Каталоги: услуг названо по-человечески %s', fixed)
    return fixed


def drop_repeats(env):
    """«Ищу самосвал…» заводился в каждую выкатку: остаётся самая ранняя."""
    Resource = env['coop.resource'].sudo().with_context(active_test=False)
    copies = Resource.search(DEMO + [('name', '=like', 'Ищу самосвал для вывоза грунта на месяц%'),
                              ('is_project_need', '=', False)], order='id')[1:]
    used = env['coop.deal'].sudo().search([('resource_id', 'in', copies.ids)]).resource_id
    used |= env['coop.project.contribution'].sudo().search(
        [('resource_id', 'in', copies.ids)]).resource_id
    gone = copies - used
    count = len(gone)
    gone.unlink()
    _logger.info('Каталоги: повторов снято %s', count)
    return count
