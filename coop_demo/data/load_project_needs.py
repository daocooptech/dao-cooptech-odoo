def diversify_project_needs(env, min_needs=4, max_needs=12):
    """Довести потребности проекта до правдоподобного объёма и разброса.

    Идёт по проектам в сборе и в запуске, считает, чего им не хватает по
    видам (все четыре: материальные, оборудование, труд, деньги) и по
    сумме (должна сходиться с required_total — от него считается пай), и
    добавляет недостающее. Существующие потребности не трогает: только
    читает их, чтобы не завести то же самое дважды. Безвреден при
    повторном запуске — проект, у которого уже четыре и больше
    потребности и закрыты оба пустовавших вида, пропускается.
    """
    Resource = env['coop.resource'].sudo()
    Collect = env['coop.project'].sudo()
    Partner = env['res.partner'].sudo()

    projects = Collect.search(
        [('state', 'in', ('gathering', 'running'))], order='id')
    if not projects:
        _logger.info('Разброс потребностей: проектов в сборе или запуске нет')
        return 0

    rnd = random.Random(20260915)
    сделано = пропущено = 0

    for project in projects:
        if not project.required_total:
            continue

        existing = Resource.search([
            ('project_id', '=', project.id),
            ('listing_type', '=', 'request'),
        ])
        типы = set(existing.mapped('resource_type'))
        if len(existing) >= min_needs and {'labour', 'financial'} <= типы:
            пропущено += 1
            continue

        existing_sum = sum(existing.mapped('price'))
        remaining = project.required_total - existing_sum
        if remaining <= 0:
            continue

        занято = set(existing.mapped('name'))
        target = rnd.randint(min_needs, max_needs)

        хотим_труд = 'labour' not in типы and rnd.random() < 0.92
        хотим_деньги = 'financial' not in типы and rnd.random() < 0.92
        слоты = []
        if хотим_труд:
            слоты.append('labour')
        if хотим_деньги:
            слоты.append('financial')
        новых = max(target - len(existing), len(слоты))
        веса_видов = ['material'] * 3 + ['equipment'] * 3 + ['labour'] * 2 + ['financial']
        while len(слоты) < новых:
            слоты.append(rnd.choice(веса_видов))

        # Балансир — тот слот, чья цена в конце подгоняется под остаток
        # бюджета, а не собственный правдоподобный диапазон: финансовый,
        # если есть (резерв естественно растёт вместе со сборами), иначе
        # оборудование или материал (там остаток превращается в
        # количество), иначе — что осталось.
        баланс = None
        for вид in ('financial', 'equipment', 'material', 'labour'):
            индексы = [i for i, s in enumerate(слоты) if s == вид]
            if индексы:
                баланс = индексы[-1]
                break
        if баланс is None:
            баланс = len(слоты) - 1

        profile = _профиль_проекта(project)
        строки = [None] * len(слоты)
        pools = {}

        for i, rtype in enumerate(слоты):
            if i == баланс:
                continue
            if rtype not in pools:
                pools[rtype] = _собрать_позиции(profile, rtype, занято)
                rnd.shuffle(pools[rtype])
            кандидаты = pools[rtype]
            if кандидаты:
                позиция = кандидаты.pop()
                занято.add(позиция[0])
            else:
                позиция = _ЖЁСТКИЙ_ЗАПАСНОЙ[rtype]
            имя, цена, ед = _цена_позиции(позиция, rnd)
            строки[i] = (rtype, имя, цена, ед)

        подытог = sum(row[2] for row in строки if row)
        остаток = remaining - подытог
        if остаток < remaining * 0.05:
            # Остальные позиции забрали почти весь бюджет — ужимаем их,
            # чтобы балансиру было куда расти не в минус.
            коэффициент = (remaining * 0.7) / подытог if подытог else 0
            подытог = 0
            for i, row in enumerate(строки):
                if row is None or i == баланс:
                    continue
                rtype, имя, цена, ед = row
                цена = _round_nice(цена * коэффициент)
                строки[i] = (rtype, имя, цена, ед)
                подытог += цена
            остаток = remaining - подытог

        цель_балансира = max(остаток, remaining * 0.05)
        вид_балансира = слоты[баланс]
        if вид_балансира == 'financial':
            имя = РЕЗЕРВ if РЕЗЕРВ not in занято else РЕЗЕРВ_ЗАПАСНОЙ
            цена = _round_nice(цель_балансира)
            ед = ''
        else:
            запас = (pools.get(вид_балансира) or []) + _собрать_позиции(
                profile, вид_балансира, занято) + _собрать_позиции(
                'general', вид_балансира, занято)
            запас_с_кол = [к for к in запас if к[1] is not None]
            позиция = (запас_с_кол or запас or [_ЖЁСТКИЙ_ЗАПАСНОЙ[вид_балансира]])[0]
            имя, цена, ед = _цена_под_остаток(позиция, цель_балансира, rnd)
        занято.add(имя)
        строки[баланс] = (вид_балансира, имя, цена, ед)

        участники = project.contribution_ids.mapped('partner_id') - project.partner_id
        if not участники:
            участники = Partner.search([
                ('coop_is_participant', '=', True), ('is_company', '=', False),
                ('id', '!=', project.partner_id.id)], limit=20)

        for row in строки:
            if row is None:
                continue
            rtype, имя, цена, ед = row
            manager = (участники[rnd.randrange(len(участники))]
                       if участники and rnd.random() < 0.33 else False)
            with env.cr.savepoint():
                Resource.create({
                    'name': имя,
                    'listing_type': 'request',
                    'resource_type': rtype,
                    'project_id': project.id,
                    'owner_id': project.partner_id.id,
                    'need_manager_id': manager.id if manager else False,
                    'city': project.city,
                    'price': цена,
                    'price_kind': 'to',
                    'price_unit_label': ед,
                    'description': '<p>Потребность проекта «%s».</p>' % project.name,
                    'state': 'published',
                    'category_id': _рубрика_ресурса(env, имя),
                })
                сделано += 1

    _logger.info('Разброс потребностей: заведено %s, проектов пропущено %s',
                 сделано, пропущено)
    return сделано
