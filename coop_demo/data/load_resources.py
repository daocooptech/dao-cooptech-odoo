def _photo_by_name(name):
    """Имя файла снимка по названию объявления, или пусто."""
    низ = name.lower()
    for ключи, файл in PHOTO_RULES:
        if any(ключ in низ for ключ in ключи):
            return файл
    return ''


def _category_by_name(name):
    """Рубрика и её корень по названию объявления, или пара пустых."""
    низ = name.lower()
    for ключи, рубрика in CATEGORY_RULES:
        if any(ключ in низ for ключ in ключи):
            return CATEGORY_PARENTS.get(рубрика), рубрика
    return None, None


def _extra_rows(rows, extra):
    cities = sorted({row['city'] for row in rows if row.get('city')})
    # Образец берётся среди оборудования, а не среди всех подряд: в
    # доборе одни машины и станки, а строка копируется целиком — тип,
    # категория, единица цены. От случайного образца мотопомпа выходила
    # материалом с ценой за килограмм, и группировка по типу товара на
    # бирже показывала прицепы среди сыпучих грузов.
    pool = [row for row in rows if row.get('type') == 'Оборудование'] or rows
    extras = []
    for i in range(extra):
        source = pool[(i * 7) % len(pool)]
        city = cities[(i * 5) % len(cities)] if cities else ''
        row = dict(source)
        row['name'] = '%s — %s' % (EXTRA_TITLES[i % len(EXTRA_TITLES)], city)
        row['city'] = city
        row['promoted'] = False
        extras.append(row)
    return extras


def load_resources(env, extra=45):
    with open(os.path.join(HERE, 'resources.json'), encoding='utf-8') as fh:
        rows = json.load(fh)
    rows = rows + _extra_rows(rows, extra)

    methods = {m.code: m for m in env['coop.resource.method'].search([])}
    Resource = env['coop.resource']
    Partner = env['res.partner']

    # Участники, между которыми раздаются объявления без владельца.
    # Организации идут первыми: у ресурса чаще стоит юридическое лицо, и
    # каталог, где всё принадлежит частным лицам, выглядел бы неправдой.
    owners = Partner.search([('coop_is_participant', '=', True)], order='is_company desc, id')
    if not owners:
        _logger.warning('Нет участников — ресурсы загружать не на кого')
        return

    categories = {}
    created = updated = 0

    for index, row in enumerate(rows):
        # Рубрика по названию, а из строки — только если название ни о чём
        # не говорит. Строке верить нельзя: там и наугад проставленные
        # рубрики макета, и копии образца у доборных записей.
        корень, рубрика = _category_by_name(row['name'])
        if рубрика:
            parent = _category(env, categories, корень) if корень else None
            category = _category(env, categories, рубрика, parent)
        else:
            parent = _category(env, categories, row['category']) if row['category'] else None
            category = (_category(env, categories, row['subcategory'], parent)
                        if row['subcategory'] else parent)

        method_codes = [METHODS[m] for m in row['methods'] if m in METHODS]
        method_ids = [methods[c].id for c in method_codes if c in methods]

        # Владелец: указанный в макете, иначе — по кругу из каталога.
        owner = None
        if row['owner']:
            owner = Partner.search([('name', '=', row['owner'])], limit=1)
        if not owner:
            owner = owners[index % len(owners)]

        values = {
            'name': row['name'],
            'listing_type': 'request' if row['listing'] == 'Спрос' else 'offer',
            'resource_type': TYPES.get(row['type'], 'material'),
            'category_id': category.id if category else False,
            'method_ids': [(6, 0, method_ids)],
            'owner_id': owner.id,
            'city': row['city'],
            'price': row['price'],
            'price_kind': row['price_kind'],
            'price_unit_label': row['price_unit'],
            'state': 'published',
        }

        # Снимок по названию, а из строки — только если правила нет.
        # Строке верить нельзя по той же причине, что и с рубрикой: у
        # доборных записей там снимок образца.
        файл = _photo_by_name(row['name']) or (
            os.path.basename(row['image']) if row['image'] else '')
        photo = os.path.join(PHOTO_DIR, файл) if файл else ''
        if photo and os.path.exists(photo):
            with open(photo, 'rb') as fh:
                values['image_1920'] = base64.b64encode(fh.read())

        # Ключ — название вместе с городом и владельцем: в макете
        # одинаковые названия встречаются у разных участников («Сварочный
        # аппарат» и в предложении, и в спросе), и схлопывать их нельзя.
        existing = Resource.search([
            ('name', '=', row['name']),
            ('city', '=', row['city']),
            ('owner_id', '=', owner.id),
        ], limit=1)
        if existing:
            existing.write(values)
            updated += 1
        else:
            Resource.create(values)
            created += 1

    _logger.info('Каталог ресурсов: %s записей, создано %s, обновлено %s, '
                 'категорий %s', len(rows), created, updated, len(categories))
