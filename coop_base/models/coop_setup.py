# -*- coding: utf-8 -*-
"""Разовые настройки платформы, которые нельзя сделать данными.

Часть записей Odoo объявлена в базовом модуле с защитой от обновления
(noupdate). Переопределить их из своего модуля нельзя: загрузчик видит
защиту и молча пропускает правку, а на экране остаётся старое значение —
и понять по коду, почему, невозможно. Такие вещи делаются кодом.
"""
import logging

from odoo import api, models

_logger = logging.getLogger(__name__)


class CoopSetup(models.AbstractModel):
    _name = 'coop.setup'
    _description = 'Настройки платформы'

    @api.model
    def apply(self):
        self._setup_currency()
        self._setup_language()
        self._setup_home()
        self._setup_branding()
        return True

    def _setup_branding(self):
        """Имя платформы в заголовке вкладки и в интерфейсе.

        Дистрибутив Rudoo подписывает интерфейс своим именем через модуль
        дебрендинга: в заголовке вкладки стояло «Руодоо». Это имя сборки
        движка, а не платформы, и участник его нигде больше не встречает.

        Правится параметрами узла, а не самим модулем: он чужой и лежит
        в `rudoo-addons`. Правка на месте живёт до первого обновления
        дистрибутива, а параметр переживает его.

        Заголовок длинный намеренно — так его назвал владелец. На
        карточке записи движок дописывает к нему имя записи, и вкладка
        выходит длинной; зато вкладка, открытая отдельно, говорит, что
        это за платформа, а не что за сборка.
        """
        params = self.env['ir.config_parameter'].sudo()
        branding = {
            'web_debranding.new_name': 'COOPTECH',
            'web_debranding.new_title':
                'COOPTECH — Децентрализованная социально-экономическая '
                'платформа с открытым исходным кодом',
        }
        changed = []
        for key, value in branding.items():
            if params.get_param(key) != value:
                params.set_param(key, value)
                changed.append(key)
        if changed:
            _logger.info('Имя платформы в интерфейсе: %s', ', '.join(changed))

    def _setup_language(self):
        """Русский — язык платформы по умолчанию.

        Решение владельца: при регистрации человек выбирает язык, а если
        не выбрал — русский. Умолчание задаётся в двух местах, и оба
        нужны: в шаблоне новой учётной записи (по нему заводят людей из
        интерфейса) и у самой платформы (по нему говорит с человеком
        всё, что создано мимо формы регистрации — загрузчиком, письмом,
        приглашением).

        Язык, которого на узле нет, не ставим: получилась бы учётная
        запись, для которой перевода не существует, и интерфейс молча
        свалился бы обратно в английский.
        """
        Lang = self.env['res.lang'].sudo()
        russian = Lang.with_context(active_test=False).search(
            [('code', '=', 'ru_RU')], limit=1)
        if not russian:
            _logger.info('Русский язык на узле не установлен — умолчание не меняю')
            return
        if not russian.active:
            russian.active = True

        # Шаблона новой учётной записи в Odoo 19 нет: `base.default_user`
        # из базового модуля исчез, и правка «языка по умолчанию» через
        # него молча ничего не делала. Язык новой записи ставится при
        # создании — см. `res.users.create` в этом же модуле.
        params = self.env['ir.config_parameter'].sudo()
        if not params.get_param('coop.default_lang'):
            params.set_param('coop.default_lang', 'ru_RU')

    def _setup_home(self):
        """Один адрес, который всегда открывает платформу.

        Без этого `/odoo` показывает то последнее, где человек был, а
        первый вход — список приложений Odoo. Оба варианта заставляют
        каждый раз искать, куда идти, и просить ссылку на нужный экран.

        **Домашняя — «Моя страница».** Решение владельца от 14 сентября
        2026: после ввода логина и пароля человек попадает на свою
        страницу. Это верно и по смыслу: первое, что человек видит, —
        его собственные владения и то, что требует его внимания, а не
        каталог чужих людей.

        Раньше домашним стоял каталог людей — первый перенесённый
        раздел, за неимением своей страницы. Тех, у кого стоит он,
        переводим: это было наше умолчание, а не выбор человека. А вот
        выбравшим себе что-то третье не мешаем — своё решение человека
        важнее нашего.

        Умолчание задаётся и в шаблоне новой учётной записи: без этого
        первый вход нового участника снова упирается в список
        приложений Odoo.
        """
        Users = self.env['res.users'].sudo()
        home = self.env.ref(
            'coop_profile.action_coop_my_page', raise_if_not_found=False)
        previous = self.env.ref(
            'coop_people.action_coop_people', raise_if_not_found=False)
        # «Моей страницы» может ещё не быть: `coop.setup.apply`
        # вызывается и из coop_base, до того как модуль профиля загружен.
        # Тогда домашним остаётся прежний каталог, а профиль перезапустит
        # настройку сам, когда загрузится.
        home = home or previous
        if not home:
            return

        users = Users.search([('share', '=', False), ('action_id', '=', False)])
        if previous and previous != home:
            users |= Users.search([('share', '=', False),
                                   ('action_id', '=', previous.id)])
        if users:
            users.write({'action_id': home.id})
            _logger.info('Домашний экран «%s» задан для %s учётных записей',
                         home.name, len(users))

        # Новым учётным записям домашний ставится при создании: шаблона,
        # который можно было бы поправить один раз, в Odoo 19 нет.

        # Ссылки, которые Odoo рассылает в письмах и уведомлениях, строятся
        # от этого параметра. Незакреплённый, он переписывается адресом
        # последнего входа — и в письме оказывается адрес, по которому
        # никто больше не зайдёт.
        params = self.env['ir.config_parameter'].sudo()
        if not params.get_param('web.base.url.freeze'):
            params.set_param('web.base.url.freeze', 'True')

    def _setup_currency(self):
        """Знак рубля вместо «руб».

        В макете цены написаны через ₽, и разнобой между макетом и
        движком читается как небрежность. Правится сама валюта, а не
        каждое место показа: иначе знак пришлось бы дублировать во всех
        карточках, списках и отчётах.
        """
        rub = self.env['res.currency'].sudo().with_context(
            active_test=False).search([('name', '=', 'RUB')], limit=1)
        if rub and rub.symbol != '₽':
            rub.write({'symbol': '₽', 'position': 'after'})
            _logger.info('Знак рубля установлен: ₽')
