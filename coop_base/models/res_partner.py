# -*- coding: utf-8 -*-
from odoo import fields, models


class ResPartner(models.Model):
    """Тип организации.

    Одним `is_company` не обойтись: кооператив, рабочая группа платформы и
    обычная компания живут по разным правилам, и права выдаются по-разному.
    Тип хранится у партнёра, а не у членства: он свойство организации, а не
    отношений с ней.
    """
    _inherit = 'res.partner'

    coop_org_type = fields.Selection([
        ('coop', 'Кооператив'),
        ('consumer_coop', 'Потребительское общество'),
        ('nonprofit', 'Некоммерческая организация'),
        ('commercial', 'Коммерческая организация'),
        ('dao', 'ДАО'),
        ('platform', 'Рабочая группа платформы'),
    ], string='Тип организации', tracking=True)
