# -*- coding: utf-8 -*-
import logging

from odoo import api, models

_logger = logging.getLogger(__name__)

# Что размораживаем. Только своё: чужие модули помечают записи «не
# обновлять» осознанно, и лезть в них нельзя.
MODULE_PREFIX = 'coop_'
MODELS = ('ir.rule', 'res.groups')


class CoopSecurityUnfreeze(models.AbstractModel):
    """Снять с наших правил доступа пометку «не обновлять».

    Пометка `noupdate` запоминается в базе при первой загрузке записи и
    живёт там дальше сама по себе: убрать её из XML недостаточно —
    обновление модуля смотрит на сохранённый флаг, а не на файл.

    Пока флаг стоит, любая правка правила доступа молча не доезжает до
    узла, и правило продолжает работать в прежнем, ошибочном виде. Именно
    так и вышло с правкой объявлений от имени организации: домены в файлах
    были исправлены, в базе остались старыми, и представитель организации
    по-прежнему не мог отредактировать её объявление.

    Правила доступа — код платформы, а не настройка узла. Если
    администратор подстроит правило под себя, обновление модуля вернёт
    нашу редакцию: так и задумано.
    """
    _name = 'coop.security.unfreeze'
    _description = 'Разморозка правил доступа'

    @api.model
    def apply(self):
        data = self.env['ir.model.data'].sudo().search([
            ('module', '=like', MODULE_PREFIX + '%'),
            ('model', 'in', list(MODELS)),
            ('noupdate', '=', True),
        ])
        if not data:
            return True
        _logger.info('Снимаю «не обновлять» с %s записей прав доступа', len(data))
        data.write({'noupdate': False})
        return True
