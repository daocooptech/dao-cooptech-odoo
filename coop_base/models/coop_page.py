# -*- coding: utf-8 -*-
"""Переход с полки на страницу записи.

Полка на карточке участника — это встроенный канбан по связанному полю.
По умолчанию щелчок по карточке открывает запись во всплывающем окне, и
для полки это неверно дважды.

Во-первых, в макете полка — витрина ссылок: человек нажимает на название
и попадает на страницу, откуда можно идти дальше. Окно обрывает путь: из
него нельзя ни подписаться, ни посмотреть соседние полки, ни дать ссылку
другому.

Во-вторых, часть полок перечисляет не сами сущности, а связки — членство
в организации, участие в сообществе. Карточка показывает организацию, а
запись под ней — членство, и окно открывает именно членство. Когда
нарисованное и перечисляемое расходятся, поведение по умолчанию всегда
достаётся перечисляемому.

Примесь задаёт обе настройки объявлением, а не кодом: `_coop_page_view` —
каким представлением открывать страницу, `_coop_page_field` — чья это
страница, если не своя.
"""

from odoo import api, fields, models, _
from odoo.exceptions import UserError


class CoopPageMixin(models.AbstractModel):
    _name = 'coop.page.mixin'
    _description = 'Переход с полки на страницу записи'

    # Могу ли я править эту запись — один ответ на все страницы портала.
    #
    # Нужен карандашам: правка по месту показывает кнопку только тому,
    # кто может писать, а спрашивать об этом каждое поле по-своему значит
    # получить столько ответов, сколько полей. Право берём у самого
    # движка — у прав доступа и правил записи, — а не выводим из
    # владельца: правило уже описано в `security/`, и второе описание
    # рядом рано или поздно разойдётся с первым.
    coop_can_edit = fields.Boolean(
        string='Могу править', compute='_compute_coop_can_edit')

    @api.depends_context('uid')
    def _compute_coop_can_edit(self):
        for record in self:
            record.coop_can_edit = bool(record.id) and record.has_access('write')

    # Представление страницы по внешнему идентификатору. Пусто — движок
    # возьмёт форму по умолчанию. Задавать стоит везде, где у модели форм
    # больше одной: у ресурса их три, и страницей работает не любая.
    _coop_page_view = ''

    # Поле-ссылка на того, чья это страница. Пусто — страница своя.
    # Заполняется у связок: членство ведёт на организацию, участие — на
    # сообщество.
    _coop_page_field = ''

    def _coop_page_view_ref(self):
        """Каким представлением открывается страница этой записи.

        Отдельным методом, а не только полем: у контакта страница зависит
        от самой записи — у человека одна, у организации другая. Спрашивают
        всегда ту запись, чью страницу открывают, поэтому связке довольно
        назвать поле: чем открыть, решит тот, на кого она ведёт.
        """
        return self._coop_page_view

    def action_coop_open_page(self):
        """Открыть страницу записи вместо всплывающего окна."""
        self.ensure_one()
        запись = self[self._coop_page_field] if self._coop_page_field else self
        if not запись:
            raise UserError(_('Запись, на которую ведёт карточка, не найдена.'))
        имя = (запись._coop_page_view_ref()
               if hasattr(запись, '_coop_page_view_ref') else self._coop_page_view)
        # Ссылка мягкая: модель и представление живут в разных модулях, и
        # зависимости между ними может не быть. Без представления страница
        # откроется формой по умолчанию — это хуже вида, но не ошибка
        # «внешний идентификатор не найден» вместо страницы.
        вид = self.env.ref(имя, raise_if_not_found=False) if имя else None
        return {
            'type': 'ir.actions.act_window',
            'name': запись.display_name,
            'res_model': запись._name,
            'res_id': запись.id,
            'view_mode': 'form',
            'views': [(вид.id if вид else False, 'form')],
            'target': 'current',
        }
