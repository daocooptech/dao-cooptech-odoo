# -*- coding: utf-8 -*-
from odoo import fields, models


class CoopPower(models.Model):
    """Полномочие внутри организации.

    Роль и полномочие — разные вещи, и до сих пор они были слиты в одно
    поле. Роль отвечает на вопрос «на каком основании человек здесь»:
    учредитель, пайщик, наёмный сотрудник. Основание одно по определению —
    нельзя быть принятым и как пайщик, и как наёмный по одному и тому же
    решению.

    Полномочие отвечает на другой вопрос — «что ему позволено делать», — и
    их у одного человека сколько угодно. Председатель бывает
    одновременно казначеем и пайщиком, а у сотрудника отдела маркетинга
    нет доступа к бухгалтерии, как у бухгалтера — к управлению сайтом.
    Одним полем это не выражается: пришлось бы заводить роль на каждое
    сочетание.

    Полномочие — не группа Odoo. Группа глобальна: выдав её, вы выдадите
    полномочие сразу во всех организациях. А «казначей в кооперативе А и
    просто пайщик в Б» — это норма, а не исключение. Поэтому полномочие
    живёт в членстве, а правила доступа смотрят на состав членства.
    """
    _name = 'coop.power'
    _description = 'Полномочие в организации'
    _order = 'sequence, id'

    name = fields.Char(string='Полномочие', required=True, translate=True)
    code = fields.Char(
        string='Код', required=True,
        help='По коду полномочие ищут правила доступа. Менять его после '
             'установки нельзя — правила перестанут его находить.')
    sequence = fields.Integer(string='Порядок', default=10)
    description = fields.Text(string='Что открывает', translate=True)

    # Полномочие, которое по своей природе принадлежит одному человеку.
    # Право подписи без доверенности — именно такое: двух единоличных
    # исполнительных органов не бывает.
    is_exclusive = fields.Boolean(
        string='Только одному',
        help='Такое полномочие в организации может быть у одного человека.')

    # Ревизия проверяет и не участвует в том, что проверяет. Полномочия с
    # этой пометкой ей не выдаются.
    is_executive = fields.Boolean(
        string='Исполнительное', default=True,
        help='Полномочия, которыми что-то делают, а не смотрят. '
             'Ревизионной комиссии не выдаются: проверяющий не должен быть '
             'участником того, что проверяет.')

    _sql_constraints = [
        ('code_uniq', 'unique(code)', 'Полномочие с таким кодом уже есть.'),
    ]
