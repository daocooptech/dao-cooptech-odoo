# -*- coding: utf-8 -*-
"""Справочник учебных заведений.

Владелец 15 сентября 2026, на вопрос откуда брать сокращённое название:
«из каталога учебных заведений страны (в данном случае рф)».

Сокращение нельзя вывести из полного названия: «Сибирский федеральный
университет» — СФУ, а «Иркутский филиал Московского государственного
технического университета гражданской авиации» — ИФ МГТУ ГА, и по первым
буквам ни то ни другое не получается. Аббревиатура — свойство заведения,
а не правило письма, и хранить её надо рядом с названием.

Справочник, а не свободная строка у каждого участника, ещё и потому, что
по учебному заведению люди находят друг друга. Сто человек, написавших
«СФУ», «Сиб. федеральный», «Сибирский федеральный ун-т» и «СибФУ», друг
друга не найдут никогда.

Свободная строка при этом остаётся: справочник заведомо неполон — в
России тысячи заведений, — и участник, чьего в списке нет, должен уметь
вписать своё руками. Поле `name` у записи об образовании никуда не
делось и работает запасным.
"""

from odoo import api, fields, models


class CoopInstitution(models.Model):
    _name = 'coop.institution'
    _description = 'Учебное заведение'
    _order = 'kind, name'

    name = fields.Char('Полное название', required=True, index=True)
    short_name = fields.Char(
        'Сокращённое название', required=True, index=True,
        help='Как заведение называют в обиходе: СФУ, МГУ, ИФКАТТ.')
    kind = fields.Selection([
        ('higher', 'Высшее'),
        ('college', 'Профессиональное'),
        ('school', 'Среднее'),
        ('courses', 'Дополнительное'),
    ], string='Ступень', required=True, default='higher', index=True,
        help='Какую ступень образования заведение даёт. Подставляется в '
             'запись участника, чтобы он не выбирал её вручную.')
    city = fields.Char('Город', index=True)
    active = fields.Boolean(default=True)

    _sql_constraints = [
        # Два одинаковых сокращения в одном городе — верный признак того,
        # что справочник заполнили дважды.
        ('coop_institution_short_city_uniq',
         'unique(short_name, city)',
         'Такое сокращённое название в этом городе уже есть.'),
    ]

    @api.depends('name', 'short_name', 'city')
    def _compute_display_name(self):
        """В списке — сокращение, а следом полное: выбирают по первому,
        а убеждаются, что не перепутали, по второму.
        """
        for record in self:
            parts = [record.short_name or record.name or '']
            if record.name and record.name != record.short_name:
                parts.append('— %s' % record.name)
            if record.city:
                parts.append('· %s' % record.city)
            record.display_name = ' '.join(parts)
