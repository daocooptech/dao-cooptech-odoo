# -*- coding: utf-8 -*-
"""Доверие и счётчики сделок у участника.

Поля лежат в `coop_base` рядом друг с другом, а считаются здесь: сделка и
отзыв живут в этом модуле, и базовому знать о них незачем.

Механика владельца от 15 сентября 2026: «всего было 35 сделок, а 33 из
них положительные, отсюда процент считается». То есть доверие — доля
сделок, по которым о человеке отозвались хорошо, от всех его завершённых
сделок. Сделка без отзыва в числитель не идёт: молчание — не похвала.

До этого числа приходили из демонстрационных данных и с действительностью
не сверялись: человек с сорока завершёнными сделками мог показывать три.

Пересчёт по событию, а не вычисляемым полем: зависеть пришлось бы от
таблицы, где участник встречается двумя разными полями и где считать
нужно обе стороны сразу, — Odoo такую зависимость через `@api.depends` не
выражает. Событий всего три: сделка завершилась, закрылся спор, появился
отзыв.
"""

from odoo import api, models

# Какая оценка считается положительной. «Нормально» — не похвала: это
# ровно то, чего ждут по умолчанию, и записывать её в плюс значит
# ставить знак равенства между «сделал как договорились» и «сделал
# хорошо».
ПОЛОЖИТЕЛЬНЫЕ = ('4', '5')


class ResPartner(models.Model):
    _inherit = 'res.partner'

    def _coop_recompute_deal_stats(self):
        """Пересчитать сделки, положительные отзывы и доверие."""
        Deal = self.env['coop.deal'].sudo()
        Review = self.env['coop.deal.review'].sudo()
        for partner in self:
            завершённых = Deal.search_count([
                ('state', '=', 'done'),
                '|', ('party_a_id', '=', partner.id),
                ('party_b_id', '=', partner.id),
            ])
            # Считаем отзывы о человеке, а не сделки с отзывом: у сделки
            # их два, и каждый относится к своей стороне.
            с_отзывом = Review.search_count([
                ('target_id', '=', partner.id),
            ])
            хорошие = Review.search_count([
                ('target_id', '=', partner.id),
                ('rating', 'in', ПОЛОЖИТЕЛЬНЫЕ),
            ])
            partner.coop_deals_done = завершённых
            partner.coop_deals_reviewed = с_отзывом
            partner.coop_deals_positive = хорошие
            # Знаменатель — сделки с отзывом, а не все завершённые:
            # решение владельца от 15 сентября 2026. Молчание второй
            # стороны не должно снижать оценку тому, кто ничего не
            # сделал; у Дашкевича одна молчаливая сделка из шести
            # стоила семнадцати пунктов.
            #
            # Без единого отзыва доверия не ноль, а нет: ноль читается
            # как «проверен и плох», тогда как о человеке просто ещё
            # никто не высказался. На странице тогда стоит «доверие
            # пока не считается».
            partner.coop_trust = (
                round(хорошие * 100.0 / с_отзывом) if с_отзывом else 0)
        return True

    @api.model
    def _coop_recompute_all_deal_stats(self):
        """Разовый пересчёт по всем — после загрузки данных и переноса."""
        участники = self.sudo().search([])
        участники._coop_recompute_deal_stats()
        return len(участники)
